/**
 * @param {ParentNode} host where the screen is inserted
 * @param {{role?: string|null, confirmFn?: (message:string)=>boolean, notify?: (message:string, kind?:string)=>void}} [ctx]
 * @returns {{el: HTMLElement, reload: ()=>Promise<void>, getRows: ()=>any[], destroy: ()=>void}}
 */
export function mountExpensesScreen(host, ctx = {}) {
    const notify = typeof ctx.notify === 'function' ? ctx.notify : (m) => console.info('[V2 expenses]', m);
    const confirmFn = typeof ctx.confirmFn === 'function' ? ctx.confirmFn
        : (m) => (typeof window !== 'undefined' && window.confirm ? window.confirm(m) : false);
    /* الرسم يحتاج الدور وعلم الكتابة (OFF افتراضيًا)؛ الخادم يبقى الحاكم. */
    const writable = canWrite(ctx.role, FINANCE_WRITE_ROLES) && financeWriteEnabled();

    let allRows = [];
    let depts = [];
    let currency = '';
    let loading = false;
    let queued = false;          // a refresh asked for while one was running
    let deptCode = 'all';
    let saving = false;
    let editing = null;          // raw row whose form is open (null when closed)

    host.insertAdjacentHTML('beforeend', template(firstOfMonth(), riyadhToday()));
    const el = host.lastElementChild;
    const q = (sel) => el.querySelector(sel);
    const countEl = q('[data-v2-count]');
    const summaryEl = q('[data-v2-summary]');
    const clearBtn = q('[data-v2-clear]');
    const formHost = q('[data-v2-form]');

    const table = createDataTable({
        caption: 'سجل المصروفات — بيانات حية',
        mode: 'client',
        pageSize: 50,
        stickyHeader: true,
        emptyMessage: 'لا توجد مصروفات في الفترة المحددة',
        emptyHint: 'وسّع الفترة أو اعرض الكل.',
        rowKey: (row) => row.id,
        columns: [
            {
                key: 'desc', header: 'البيان', sortable: true, filterable: true,
                render: (row) => (row.desc ? esc(row.desc) : `<span class="erp-text-muted">—</span>`),
            },
            { key: 'deptName', header: 'القسم', sortable: true, filterable: true, width: '150px' },
            {
                key: 'amount', header: 'المبلغ', type: 'number', sortable: true,
                width: '150px', align: 'end', value: (row) => row.amount,
                render: (row) => moneyCell(row.amount, currency),
            },
            {
                key: 'kindLabel', header: 'النوع', sortable: true, filterable: true, width: '130px',
                value: (row) => row.kindLabel,
                render: (row) => `${kindBadge(row.kind)}${row.auto ? ' <span class="erp-text-xs erp-text-muted" title="لا يمكن تعديل أو حذف المصروفات التلقائية">(مقفول)</span>' : ''}`,
            },
            {
                key: 'date', header: 'التاريخ', sortable: true, filterable: true,
                width: '120px', align: 'center', className: 'erp-tnum',
            },
            ...(writable ? [{
                key: 'actions',
                header: 'إجراءات',
                width: '170px',
                align: 'end',
                value: () => '',
                render: (row) => (row.auto
                    ? `<span class="erp-text-muted" title="مصروف تلقائي — لا يُعدَّل ولا يُحذف" aria-label="مصروف تلقائي مقفول">—</span>`
                    : `
                  <span class="erp-row-wrap">
                    <button type="button" class="erp-btn erp-btn--sm" data-v2-act="edit" data-id="${esc(row.id)}" data-name="${esc(row.desc || '')}">
                      <i class="ji" data-i="pencil" aria-hidden="true"></i><span>تعديل</span>
                    </button>
                    <button type="button" class="erp-btn erp-btn--sm erp-btn--danger" data-v2-act="delete" data-id="${esc(row.id)}" data-name="${esc(row.desc || '')}">
                      <i class="ji" data-i="trash" aria-hidden="true"></i><span>حذف</span>
                    </button>
                  </span>`),
            }] : []),
        ],
    });

    q('[data-v2-table]').appendChild(table.el);

    function deptNameOf(code) {
        const d = depts.find((x) => String(x.code) === String(code));
        return d ? String(d.name) : (code ? String(code) : '—');
    }

    function decorate(r) {
        const kind = expenseKind(r);
        return {
            ...r,
            deptName: deptNameOf(r.deptId),
            kind,
            kindLabel: EXPENSE_KIND_AR[kind] || kind,
            auto: !!r.autoGenerated,
        };
    }

    function viewRows() {
        const from = q('#v2exp-from').value;
        const to = q('#v2exp-to').value;
        const rows = allRows.filter((r) => {
            if (deptCode !== 'all' && String(r.deptId) !== deptCode) {return false;}
            if (from && r.date < from) {return false;}
            if (to && r.date > to) {return false;}
            return true;
        }).map(decorate);
        return { rows, filtered: !!(from || to || deptCode !== 'all') };
    }

    function paint() {
        const { rows, filtered } = viewRows();
        const total = rows.reduce((s, r) => s + num(r.amount), 0);
        const m = formatMoney(total, currency);
        summaryEl.textContent = `إجمالي المعروض ${m.amount}${currency ? ` ${currency}` : ''}`
            + ` · ${formatInt(rows.length)} مصروفًا`;
        countEl.textContent = rows.length ? `(${formatInt(rows.length)})` : '';
        clearBtn.hidden = !filtered;
        table.setRows(rows);
    }

    async function reload() {
        if (loading) {queued = true; return;}
        loading = true;
        table.setLoading(true);
        try {
            const [exps, deptList, cur] = await Promise.all([
                fetchExpenses(),
                fetchDepartments().catch(() => []),
                fetchCurrency().catch(() => ''),
            ]);
            if (!el.isConnected) {return;}          // destroyed while in flight
            currency = String(cur ?? '');
            depts = deptList;
            allRows = exps;
            const sel = q('#v2exp-dept');
            if (sel) {
                sel.innerHTML = `<option value="all">كل الأقسام</option>`
                    + depts.map((d) => `<option value="${esc(d.code)}">${esc(d.name)}</option>`).join('');
                sel.value = deptCode;
            }
            paint();
        } catch (e) {
            if (!el.isConnected) {return;}
            allRows = [];
            table.setRows([]);
            summaryEl.textContent = '';
            countEl.textContent = '';
            table.setError(e && e.message === 'UNAUTHORIZED'
                ? 'انتهت الجلسة — سجّل الدخول في النظام الحالي ثم أعد فتح الوضع الحيّ.'
                : (e && e.code === 'FORBIDDEN'
                    ? 'لا صلاحية لعرض المصروفات بهذا الحساب — القرار للخادم وحده.'
                    : `تعذّر تحميل المصروفات: ${(e && e.message) || 'خطأ'}`));
        } finally {
            loading = false;
            if (queued && el.isConnected) {
                queued = false;
                reload();                            // the newest read wins
            }
        }
    }

    /* ── Form (in-card edit panel — no legacy modal, no inline handler) ─ */
    const EXP_FIELDS = ['desc', 'deptId', 'category', 'amount', 'date', 'notes'];
    const EXP_CATEGORIES = ['مواد خام', 'رواتب', 'تشغيل', 'أخرى'];

    function rowOf(id) {
        return allRows.find((r) => String(r.id) === String(id)) || null;
    }

    /** قسم غائب من الدليل (محذوف أو رمز غريب) يُعرض كما هو — لا يُخترع اسم بديل. */
    function deptOptions(selected) {
        const cur = String(selected ?? '');
        const known = depts.map((d) => `<option value="${esc(d.code)}"${String(d.code) === cur ? ' selected' : ''}>${esc(d.name)}</option>`).join('');
        if (cur && depts.some((d) => String(d.code) === cur)) {return known;}
        return (cur ? '' : '<option value="" selected>— بلا قسم —</option>')
            + known + (cur ? `<option value="${esc(cur)}" selected>${esc(cur)}</option>` : '');
    }

    /** فئة مجهولة تُعرض كما هي ولا تُستبدل بأول الخيارات: legacy كان يسقط
     *  صامتًا إلى «مواد خام» عند الحفظ — ذلك تغيير بيانات لا يجوز هنا. */
    function categoryOptions(selected) {
        const cur = String(selected ?? '');
        const known = EXP_CATEGORIES.map((c) => `<option value="${esc(c)}"${c === cur ? ' selected' : ''}>${esc(c)}</option>`).join('');
        if (cur && EXP_CATEGORIES.includes(cur)) {return known;}
        return (cur ? '' : '<option value="" selected>— بلا فئة —</option>')
            + known + (cur ? `<option value="${esc(cur)}" selected>${esc(cur)}</option>` : '');
    }

    function formHtml() {
        const row = editing || {};
        const val = (k) => (row[k] !== undefined && row[k] !== null ? String(row[k]) : '');
        return `
          <form class="erp-stack" data-v2-form-el novalidate>
            <h4 class="erp-card__title">تعديل مصروف</h4>
            <div class="erp-field">
              <label class="erp-label" for="v2exp-f-desc">البيان *</label>
              <input class="erp-input" id="v2exp-f-desc" name="desc" value="${esc(val('desc'))}">
            </div>
            <div class="erp-row-wrap">
              <div class="erp-grow">
                <label class="erp-label" for="v2exp-f-dept">القسم *</label>
                <select class="erp-select" id="v2exp-f-dept" name="deptId">${deptOptions(val('deptId'))}</select>
              </div>
              <div class="erp-grow">
                <label class="erp-label" for="v2exp-f-category">الفئة</label>
                <select class="erp-select" id="v2exp-f-category" name="category">${categoryOptions(val('category'))}</select>
              </div>
            </div>
            <div class="erp-row-wrap">
              <div class="erp-grow">
                <label class="erp-label" for="v2exp-f-amount">المبلغ *</label>
                <input class="erp-input erp-input--ltr" id="v2exp-f-amount" name="amount" type="number" step="0.01" value="${esc(val('amount'))}">
              </div>
              <div class="erp-grow">
                <label class="erp-label" for="v2exp-f-date">التاريخ *</label>
                <input class="erp-input erp-input--ltr" id="v2exp-f-date" name="date" type="date" value="${esc(val('date'))}">
              </div>
            </div>
            <div class="erp-field">
              <label class="erp-label" for="v2exp-f-notes">ملاحظات</label>
              <input class="erp-input" id="v2exp-f-notes" name="notes" value="${esc(val('notes'))}">
            </div>
            <p class="erp-text-sm erp-text-muted">حقول النظام (التوليد التلقائي ونوع القيد) لا تُرسل في التعديل — قفل السجل ونوعه من صميم النظام لا من يد المشغّل.</p>
            <div class="erp-error" data-v2-form-error role="alert"></div>
            <div class="erp-row-wrap">
              <span class="erp-grow"></span>
              <button type="button" class="erp-btn" data-v2-form-cancel>إلغاء</button>
              <button type="submit" class="erp-btn erp-btn--primary" data-v2-form-save>
                <i class="ji" data-i="save" aria-hidden="true"></i><span>حفظ</span>
              </button>
            </div>
          </form>`;
    }

    function openForm(id) {
        if (!writable) {return;}
        const row = rowOf(id);                      // raw record, not the display row
        if (!row) {return;}
        if (row.autoGenerated) {return;}            // قفل legacy finance.js:217
        editing = { ...row };
        formHost.innerHTML = formHtml();
        formHost.hidden = false;
        formHost.querySelector('[name="desc"]')?.focus();
    }

    function closeForm() {
        editing = null;
        formHost.hidden = true;
        formHost.innerHTML = '';
    }

    function readForm() {
        const out = {};
        const form = formHost.querySelector('[data-v2-form-el]');
        if (!form) {return out;}
        for (const key of EXP_FIELDS) {
            const input = form.querySelector(`[name="${key}"]`);
            out[key] = input ? input.value : '';
        }
        return out;
    }

    function showFormErrors(errors) {
        const box = formHost.querySelector('[data-v2-form-error]');
        if (!box) {return;}
        box.textContent = errors.map((e) => e.message).join(' · ');
        const form = formHost.querySelector('[data-v2-form-el]');
        if (!form) {return;}
        for (const key of EXP_FIELDS) {
            const input = form.querySelector(`[name="${key}"]`);
            if (input) {input.setAttribute('aria-invalid', errors.some((e) => e.field === key) ? 'true' : 'false');}
        }
    }

    async function submitForm(event) {
        event.preventDefault();
        if (saving || !editing || editing.id == null) {return;}
        const form = readForm();
        const errors = validateExpenseForm(form);
        if (errors.length) {
            showFormErrors(errors);
            return;
        }
        showFormErrors([]);
        saving = true;
        const saveBtn = formHost.querySelector('[data-v2-form-save]');
        if (saveBtn) {saveBtn.disabled = true;}
        try {
            await updateExpense(editing.id, form);
            if (!el.isConnected) {return;}           // navigated away mid-save
            notify(`تم تعديل مصروف «${String(form.desc).trim()}»`);
            closeForm();
            await reload();
        } catch (e) {
            if (!el.isConnected) {return;}
            // The server's sentence stays verbatim — refusal is the operator's
            // to fix, not ours to re-word.
            showFormErrors([{ field: '', message: (e && e.message) || 'فشل الحفظ' }]);
        } finally {
            saving = false;
            const btn = formHost.querySelector('[data-v2-form-save]');
            if (btn) {btn.disabled = false;}
        }
    }

    /** الحذف يسأل أولًا (مرآة legacy finance.js:240) — الرفض لا يرسل نداءً،
     *  والتلقائي يُرفض هنا ولو جاء الزر من مكان آخر (مرآة finance.js:239). */
    async function runDelete(id, name) {
        if (saving) {return;}
        const row = rowOf(id);
        if (row && row.autoGenerated) {return;}
        if (!confirmFn(`حذف مصروف «${name || `#${id}`}»؟ لا رجعة بعد الحذف.`)) {return;}
        saving = true;
        try {
            await deleteExpense(id);
            if (!el.isConnected) {return;}           // navigated away mid-write
            notify(`تم حذف مصروف «${name || `#${id}`}»`);
            await reload();
        } catch (e) {
            if (!el.isConnected) {return;}
            notify(`فشلت العملية: ${(e && e.message) || 'خطأ'}`, 'error');
        } finally {
            saving = false;
        }
    }

    el.addEventListener('click', (event) => {
        if (event.target.closest('[data-v2-clear]')) {
            q('#v2exp-from').value = '';
            q('#v2exp-to').value = '';
            deptCode = 'all';
            const sel = q('#v2exp-dept');
            if (sel) {sel.value = 'all';}
            paint();
            return;
        }
        if (event.target.closest('[data-v2-print]')) {window.print(); return;}
        if (event.target.closest('[data-v2-reload]')) {reload(); return;}
        if (event.target.closest('[data-v2-form-cancel]')) {closeForm(); return;}
        const actBtn = event.target.closest('[data-v2-act]');
        if (actBtn) {
            if (actBtn.disabled) {return;}
            if (actBtn.dataset.v2Act === 'edit') {openForm(actBtn.dataset.id); return;}
            runDelete(actBtn.dataset.id, actBtn.dataset.name || '');
            return;
        }
        if (event.target.closest('[data-erp-retry]')) {reload();}
    });
    el.addEventListener('change', (event) => {
        if (event.target.id === 'v2exp-dept') {deptCode = event.target.value; paint(); return;}
        if (event.target.matches('#v2exp-from, #v2exp-to')) {paint();}
    });

    formHost.addEventListener('submit', submitForm);

    reload();

    return {
        el,
        reload,
        getRows: () => viewRows().rows,
        destroy() {
            table.destroy();
            el.remove();
        },
    };
}
