import { createDataTable } from '../data-display/data-table.js?v=4.9.130';
import {
    fetchExpenses, fetchDepartments, expenseKind,
    EXPENSE_KIND_AR, EXPENSE_KIND_TONE, isoDay, firstOfMonth,
} from '../data/finance-repo.js?v=4.9.130';
import { fetchCurrency, formatMoney, formatInt } from '../data/reports-repo.js?v=4.9.130';

const esc = (v) => String(v ?? '')
    .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;').replace(/'/g, '&#39;');

const num = (v) => {
    const n = Number(v);
    return Number.isFinite(n) ? n : 0;
};

function moneyCell(v, currency) {
    const m = formatMoney(v, currency);
    const neg = num(v) < 0;
    const body = `<span class="erp-num${neg ? ' erp-text-success' : ''}" dir="ltr">${m.amount}</span>`
        + (m.hasUnit ? ` <span class="erp-text-sm erp-text-muted">${esc(m.unit)}</span>` : '');
    return body;
}

/** Derived kind → the same badge shape status.js badges use. */
function kindBadge(kind) {
    const tone = EXPENSE_KIND_TONE[kind] || 'neutral';
    return `<span class="erp-badge" data-tone="${esc(tone)}">${esc(EXPENSE_KIND_AR[kind] || kind)}</span>`;
}

