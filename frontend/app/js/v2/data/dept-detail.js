import { apiFetch } from '../../core/api.js?v=4.9.131';
import { fetchRevenues, fetchExpenses, fetchDepartments, deptWithChildren, calcDeptStats, deptExpenseBreakdown } from './finance-repo.js?v=4.9.131';
import { fetchDispatches } from './dispatch-repo.js?v=4.9.131';

export const CASHIER_DEPT_MAP = {
    1: 'CAF',
    4: 'external_sales',
    5: 'external_sales',
    6: 'G',
    9: 'open_buffet',
};

export function cashierRevenueIn(revenues, cashierNos, fromDate, toDate) {
    const wanted = new Set((cashierNos || []).map((no) => `ys_cc_${no}`));
    return (revenues || []).filter((r) => {
        if (!wanted.has(String(r.deptId))) {return false;}
        if (!fromDate && !toDate) {return true;}
        const d = String(r.date || '').slice(0, 10);
        if (!d) {return false;}
        if (fromDate && d < fromDate) {return false;}
        if (toDate && d > toDate) {return false;}
        return true;
    }).reduce((s, r) => s + (Number(r.amount) || 0), 0);
}

export function deptIdentityColor(d) {
    const c = String((d && d.color) || '').trim();
    return /^#[0-9a-fA-F]{6}$/.test(c) ? c : '#D4A843';
}

/** صفوف مصروف القسم بالنطاق — للجدول (الملخص العددي من deptExpenseBreakdown). */
export function deptExpenseRows(expenses, departments, deptCode, from, to) {
    const codes = deptWithChildren(departments, deptCode);
    return (expenses || []).filter((e) => {
        if (!codes.has(String(e && e.deptId))) {return false;}
        const d = String(e.date || '').slice(0, 10);
        if (from && d < from) {return false;}
        if (to && d > to) {return false;}
        return true;
    });
}
/** أرقام الكاشيرات المسندة لقسم (يشمل فروعه — departments.js:370). */
export function mappedCashierNos(deptCode, departments) {
    const codes = deptWithChildren(departments, deptCode);
    return Object.keys(CASHIER_DEPT_MAP).filter((no) => codes.has(String(CASHIER_DEPT_MAP[no])));
}

/**
 * ملخص القسم الكامل — departments.js:361-380: إحصاءات + إيراد الكاشير
 * المسند (مع الفروع) + تفكيك المصروف + آخر 10 إيرادات/مصاريف + كل أذون
 * الفترة.
 */
export function computeDeptDetail(bundle, deptCode, from, to) {
    const { departments, revenues, expenses, dispatches } = bundle;
    const dept = (departments || []).find((d) => String(d.code) === String(deptCode));
    if (!dept) {return { found: false };}
    const codes = deptWithChildren(departments, deptCode);
    const s = { ...calcDeptStats(revenues, expenses, departments, deptCode, from, to) };
    const cashNos = mappedCashierNos(deptCode, departments);
    const cashRev = cashNos.length ? cashierRevenueIn(revenues, cashNos, from, to) : 0;
    if (cashRev > 0) {
        s.rev += cashRev;
        s.profit = s.rev - s.exp;
        s.costRatio = s.rev > 0 ? (s.exp / s.rev) * 100 : 0;
    }
    const bd = deptExpenseBreakdown(expenses, departments, deptCode, from, to);
    const inRange = (rows) => (rows || []).filter((r) => {
        const d = String(r.date || '').slice(0, 10);
        if (from && d < from) {return false;}
        if (to && d > to) {return false;}
        return true;
    });
    return {
        found: true, dept, stats: s, breakdown: bd, cashNos, cashRev,
        color: deptIdentityColor(dept),
        revenues: inRange((revenues || []).filter((r) => codes.has(String(r.deptId)))).slice().reverse().slice(0, 10),
        expenses: deptExpenseRows(expenses, departments, deptCode, from, to).slice().reverse().slice(0, 10),
        /* fetchDispatches ترجع الأحدث أولًا (desc) — بلا reverse بقي كما هو. */
        dispatches: inRange(((dispatches || []).filter((d) => codes.has(String(d.deptCode))))),
    };
}

export async function fetchDeptDetailBundle() {
    const [departments, revenues, expenses, dispatches] = await Promise.all([
        fetchDepartments(), fetchRevenues(), fetchExpenses(), fetchDispatches(),
    ]);
    return {
        departments: Array.isArray(departments) ? departments : [],
        revenues: Array.isArray(revenues) ? revenues : [],
        expenses: Array.isArray(expenses) ? expenses : [],
        dispatches: Array.isArray(dispatches) ? dispatches : [],
    };
}

export async function createRevenue({ deptId, amount, date, source, notes }) {
    if (!deptId || !(Number(amount) > 0) || !source) {throw new Error('بيانات غير صحيحة');}
    return apiFetch('/revenues', {
        method: 'POST', body: JSON.stringify({ deptId, amount: Number(amount), date, source, notes }),
    });
}

export async function createExpense({ deptId, amount, date, desc, category, notes }) {
    if (!deptId || !(Number(amount) > 0) || !desc) {throw new Error('بيانات غير صحيحة');}
    return apiFetch('/expenses', {
        method: 'POST',
        body: JSON.stringify({ deptId, amount: Number(amount), date, desc, category, notes, autoGenerated: false }),
    });
}
