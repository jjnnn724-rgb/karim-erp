/** Dept code + every descendant code — cycle-safe, same as legacy. */
export function deptWithChildren(departments, code) {
    const root = String(code);
    const out = new Set([root]);
    const kids = new Map();
    (departments || []).forEach((d) => {
        const p = d && d.parent_code ? String(d.parent_code) : '';
        const c = d && d.code !== undefined && d.code !== null ? String(d.code) : '';
        if (!p || !c || p === c) {return;}
        if (!kids.has(p)) {kids.set(p, []);}
        kids.get(p).push(c);
    });
    const stack = [root];
    while (stack.length) {
        const c = stack.pop();
        for (const k of (kids.get(c) || [])) {
            if (!out.has(k)) {out.add(k); stack.push(k);}
        }
    }
    return out;
}

const inRange = (r, from, to) => {
    if (!from && !to) {return true;}
    const d = String((r && (r.date || r.createdAt || r.created_at)) || '').slice(0, 10);
    if (!d) {return false;}
    if (from && d < from) {return false;}
    if (to && d > to) {return false;}
    return true;
};

/**
 * {materials, countAdj, operating, total} for one dept (with children) —
 * the same four buckets the legacy deptExpenseBreakdown builds.
 */
export function deptExpenseBreakdown(expenses, departments, deptCode, from, to) {
    const codes = deptWithChildren(departments, deptCode);
    const rows = (expenses || []).filter((e) => codes.has(String(e && e.deptId)) && inRange(e, from, to));
    const sum = (list) => list.reduce((s, e) => s + Number(e && e.amount || 0), 0);
    const materials = Math.max(0, sum(rows.filter(isStockMovementExpense)));
    const countAdj = sum(rows.filter(isCountCorrectionExpense));
    const operating = sum(rows.filter((e) => !isStockMovementExpense(e) && !isCountCorrectionExpense(e)));
    return { materials, countAdj, operating, total: materials + countAdj + operating, rowCount: rows.length };
}

/** {rev, exp, profit, costRatio} for one dept (with children). */
export function calcDeptStats(revenues, expenses, departments, deptCode, from, to) {
    const codes = deptWithChildren(departments, deptCode);
    const rev = (revenues || [])
        .filter((r) => codes.has(String(r && r.deptId)) && inRange(r, from, to))
        .reduce((s, r) => s + Number(r && r.amount || 0), 0);
    const exp = deptExpenseBreakdown(expenses, departments, deptCode, from, to).total;
    return { rev, exp, profit: rev - exp, costRatio: rev > 0 ? (exp / rev) * 100 : 0 };
}

/** Table + KPI roll-up for the cost-analysis screen. Pure. */
export function buildCostRows(revenues, expenses, departments, from, to) {
    const rows = (departments || []).map((d) => {
        const s = calcDeptStats(revenues, expenses, departments, d.code, from, to);
        const bd = deptExpenseBreakdown(expenses, departments, d.code, from, to);
        return { code: d.code, name: d.name, rev: s.rev, exp: s.exp, profit: s.profit, costRatio: s.costRatio, ...bd };
    });
    const totals = rows.reduce((acc, r) => ({
        rev: acc.rev + r.rev, exp: acc.exp + r.exp,
        mat: acc.mat + r.materials, cnt: acc.cnt + r.countAdj, ops: acc.ops + r.operating,
    }), { rev: 0, exp: 0, mat: 0, cnt: 0, ops: 0 });
    totals.avgCost = totals.rev > 0 ? (totals.exp / totals.rev) * 100 : 0;
    return { rows, totals };
}

/** Local YYYY-MM-DD (device calendar — same basis as the legacy today()). */
export function isoDay(offsetDays = 0, base = new Date()) {
    const d = new Date(base);
    d.setDate(d.getDate() + offsetDays);
    const p = (n) => String(n).padStart(2, '0');
    return `${d.getFullYear()}-${p(d.getMonth() + 1)}-${p(d.getDate())}`;
}

export function firstOfMonth(now = new Date()) {
    return `${riyadhToday(now).slice(0, 7)}-01`;
}

/** Current business day in Riyadh, matching the server's V2 date bounds. */
export function riyadhToday(now = new Date()) {
    const parts = new Intl.DateTimeFormat('en-CA', {
        timeZone: 'Asia/Riyadh',
        year: 'numeric',
        month: '2-digit',
        day: '2-digit',
    }).formatToParts(now);
    const values = Object.fromEntries(parts.map(({ type, value }) => [type, value]));
    return `${values.year}-${values.month}-${values.day}`;
}

