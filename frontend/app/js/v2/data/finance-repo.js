const STOCK_TYPES = ['dispatch', 'dispatch_return', 'receipt', 'stock_transfer', 'inventory_transfer', 'kitchen_return'];

const normType = (e) => String(e && (e.adjustmentType || e.adjustment_type) || '').toLowerCase();

export function isStockMovementExpense(e) {return STOCK_TYPES.includes(normType(e));}
export function isCountCorrectionExpense(e) {return normType(e) === 'count_correction';}

/**
 * expense row → display kind. Legacy wording (features/finance.js:191):
 * فرق جرد / عكس صرف / صرف مخزون / تلقائي / يدوي.
 */
export function expenseKind(e) {
    if (isCountCorrectionExpense(e)) {return 'count';}
    if (isStockMovementExpense(e)) {return Number(e && e.amount || 0) < 0 ? 'return' : 'stock';}
    if (e && e.autoGenerated) {return 'auto';}
    return 'manual';
}

