function applyI18nMaps(){
  const en = STATE.lang === 'en';
  for(const k of Object.keys(ROLES)){ if(ROLE_NAMES[k]) {ROLES[k].name = en ? ROLE_NAMES[k].en : ROLE_NAMES[k].ar;} }
  for(const k of Object.keys(ALL_PERMISSIONS.menus)){
    const m = MENU_STRINGS[k];
    if(m) {ALL_PERMISSIONS.menus[k] = `<i class=ji data-i=${m.icon}></i> ${en ? m.en : m.ar}`;}
  }
}
function applyLangAttrs(){
  const en = STATE.lang === 'en';
  document.documentElement.lang = en ? 'en' : 'ar';
  document.documentElement.dir = en ? 'ltr' : 'rtl';
  const lb = document.querySelector('.topbar-btn[data-karim-action="toggleLang"]');
  if(lb) {lb.innerHTML = '<i class="ji" data-i="globe"></i> ' + (en ? 'عربي' : 'EN');}
  applyLoginI18n();
}
function applyLoginI18n(){
  const set = (id, txt) => { const el = document.getElementById(id); if(el) {el.textContent = txt;} };
  const setPh = (id, txt) => { const el = document.getElementById(id); if(el) {el.placeholder = txt;} };
  set('loginTitle', t('login.title'));
  const sub = document.getElementById('loginSub');
  if(sub) {sub.innerHTML = t('login.sub') + ' · ' + (sub.querySelector('#loginVersion')?.outerHTML || '');}
  const luL = document.getElementById('luLabel');
  if(luL) {luL.innerHTML = '<i class="ji" data-i="user"></i> ' + t('login.user');}
  const lpL = document.getElementById('lpLabel');
  if(lpL) {lpL.innerHTML = '<i class="ji" data-i="lock"></i> ' + t('login.pass');}
  setPh('lu', t('login.user')); setPh('lp', t('login.pass'));
  const btn = document.getElementById('loginBtn');
  if(btn && !btn.disabled) {btn.innerHTML = '<i class="ji" data-i="log-in"></i> ' + t('login.btn');}
}

