/**
 * catch-weight-heuristic.js — كشف أصناف الوزن المتغير (Catch Weight)
 * ────────────────────────────────────────────────────────────────────────────
 * المشكلة: الأقسام تطلب اللحوم واللحوم المجمدة بالكرتون، والمخزن يخزنها بالوزن
 * (كجم) ووزن الكرتون الواحد متغير من شحنة لأخرى.
 * الحل: صنف "وزن متغير" — الطلب بعدد الكراتين، والصرف بالوزن الفعلي من الميزان.
 *
 * هذا الموديول هو المصدر الوحيد لقاعدة الكشف، ويُستخدم في:
 *   - إنشاء صنف عبر CRUD العام (server.js)
 *   - استيراد Excel/CSV (cashier-module/excel-import-routes.js)
 *   - المايجريشن 085 (نفس الأنماط نصًا — حافظ على التزامن عند التعديل)
 *
 * القاعدة: اسم يشبه اللحوم/الدواجن/الأسماك الطازجة + مخزون بالوزن
 * ⇒ تفعيل الوزن المتغير (وحدة التعبئة: كرتون).
 * المخزون بالكرتون أو بالحبة يبقى كما هو — الطلب والصرف فيهما متطابقان أصلًا.
 */

// أنماط أسماء اللحوم والدواجن والأسماك الطازجة ومشتقاتها (عربي + إنجليزي)
const MEAT_PATTERN = [
    // لحوم حمراء ومذبوحات
    'لحم', 'لحوم', 'عجل', 'بقر', 'بقري', 'غنم', 'خروف', 'خرفان', 'ضاني',
    'كتف', 'ضلع', 'ضلوع', 'ريش', 'فخذ', 'افخاذ', 'أفخاذ', 'وتر', 'لوة', 'لوذ',
    'ستيك', 'استيك', 'بتلو', 'سجق', 'بسطرمة', 'كفتة', 'كفته', 'كباب',
    'كوارع', 'مقادم', 'كرشة', 'ممبار', 'شحم', 'كبدة',
    // دواجن ومصنعاتها
    'دجاج', 'فروج', 'صدور', 'جناح', 'جوانح', 'أجنحة', 'ورك', 'بروستر',
    'فيليه', 'ناجت', 'نقانق', 'لانشون', 'مرتديلا', 'شاورما', 'برجر',
    // أسماك ومصنعاتها الطازجة
    'سمك', 'روبي', 'جمبري', 'كاليماري', 'بلطي', 'دنيس', 'هامور', 'كنعد',
    'ماكريل', 'سلطعون', 'كابوريا', 'استاكوزا',
    // إنجليزي
    'meat', 'beef', 'chicken', 'lamb', 'mutton', 'veal', 'fish', 'shrimp',
].join('|');

// كلمات تستبعد صنفًا رغم مطابقته للأنماط أعلاه — فئتان:
// (1) ليست لحومًا أصلًا: بهارات/توابل/حبوب/مرقة — إيجابيات كاذبة موثقة
//     من القاعدة: «بهارات تكا - للدجاج» و«جريش اصفر» (يحوي «ريش»).
// (2) لحوم تُطلب بالكيلو مباشرة بلا كرتون (قرار المالك 2026-10-05):
//     الشحم والكبدة منتجات مفتوحة تُصرف بالوزن — التفعيل التلقائي كان سيفرض
//     طلبها بالكرتون خطأً (صُحح بالمايجريشن 086). التفعيل اليدوي يظل ممكنًا
//     من شاشة الصنف لو وصلت «كبدة/شحم» معبأة كراتين يومًا.
const NON_MEAT_PATTERN = [
    'بهارات', 'بهار', 'توابل', 'خلطات', 'تتبيلة', 'تتبيله', 'أعشاب', 'اعشاب',
    'جريش', 'فريك', 'برغل', 'برجل', 'مرق', 'شوربة', 'مسحوق', 'حبوب',
    'شحم', 'كبدة',
].join('|');

// وحدات تخزين الوزن — فقط معها يُفعل الوزن المتغير (المخزون كجم والطلب كرتون)
const WEIGHT_UOM_PATTERN = 'كيلو|كيلوجرام|كجم|كغ|kg|جرام|غرام|جم|g';

const _meatRe = new RegExp(MEAT_PATTERN, 'i');
const _nonMeatRe = new RegExp(NON_MEAT_PATTERN, 'i');
const _weightUomRe = new RegExp(`^(${WEIGHT_UOM_PATTERN})$`, 'i');

/** هل وحدة التخزين وزنية (كجم/جرام)؟ */
function isWeightUnit(unit) {
    return _weightUomRe.test(String(unit || '').trim());
}

/** هل الاسم يشبه صنف لحوم/دواجن/أسماك طازجة؟ */
function looksLikeMeat(name) {
    const s = String(name || '');
    if (!s.trim()) {return false;}
    return _meatRe.test(s) && !_nonMeatRe.test(s);
}

/**
 * اقتراح إعدادات الوزن المتغير لصنف جديد.
 * @returns {object|null} حقول جاهزة للدمج في صف inventory، أو null إن لا ينطبق.
 */
function suggestCatchWeight(name, unit) {
    if (!isWeightUnit(unit) || !looksLikeMeat(name)) {return null;}
    return {
        catch_weight_enabled: true,
        inventory_uom: 'kg',
        packaging_uom: 'كرتون',
        catch_weight_uom: 'kg',
    };
}

module.exports = { MEAT_PATTERN, NON_MEAT_PATTERN, WEIGHT_UOM_PATTERN, isWeightUnit, looksLikeMeat, suggestCatchWeight };
