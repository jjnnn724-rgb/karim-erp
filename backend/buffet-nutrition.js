/** حدود الوعاء لتقسيم كمية الوصفة على الحصص */
const GUEST_LOW = 35;
const GUEST_HIGH = 40;

/**
 * يحسب القيم الغذائية للوصفة كاملة + كل حصة.
 * @param ingredients Array<{name, qty, unit}>
 * @param perPortionUsed يستعمل عند الحاجة فقط — لا هنا، القسمة داخليًا لحدّين 35/40
 */
function computeNutrition(ingredients) {
    const totals = { kcal: 0, protein: 0, carbs: 0, fat: 0, fiber: 0, sodium: 0 };
    const allergens = new Set();
    const unmatched = [];
    const matched = [];
    for (const ing of ingredients || []) {
        const key = matchIngredient(ing.name);
        const qty = Number(ing.qty) || 0;
        const grams = toGrams(qty, ing.unit);
        if (!key || grams == null) {
            if (qty > 0) {unmatched.push(String(ing.name));}
            continue;
        }
        const [kcal, protein, carbs, fat, fiber, sodium, tags] = USDA[key];
        const f = grams / 100;
        totals.kcal += kcal * f;
        totals.protein += protein * f;
        totals.carbs += carbs * f;
        totals.fat += fat * f;
        totals.fiber += fiber * f;
        totals.sodium += sodium * f;
        for (const t of tags) {allergens.add(t);}
        matched.push(key);
    }
    const round1 = (n) => Math.round(Number(n || 0) * 10) / 10;
    const perMeal = { ...totals };
    const perServingLow = {};
    const perServingHigh = {};
    for (const k of Object.keys(perMeal)) {
        perMeal[k] = Math.round(totals[k] * 10) / 10;
        perServingLow[k] = round1(totals[k] / GUEST_HIGH);
        perServingHigh[k] = round1(totals[k] / GUEST_LOW);
    }
    return {
        totals: perMeal,
        perServing: { low: perServingLow, high: perServingHigh, guestsLow: GUEST_LOW, guestsHigh: GUEST_HIGH },
        allergens: [...allergens],
        allergenLabels: [...allergens].map((a) => ALLERGEN_AR[a] || a),
        matchedCount: matched.length,
        unmatched,
        sourceNote: 'القيم تقريبية من USDA FoodData Central — SR Legacy (fdc.nal.usda.gov)، تُراجع عند التدقيق الغذائي',
        unmatchedNote: unmatched.length
            ? `مكونات غير مُغطَّاة في الجدول (${unmatched.length}): ${unmatched.slice(0, 12).join(' · ')}${unmatched.length > 12 ? ' …' : ''}`
            : null,
    };
}

/** تحويل كمية الوصفة لوزن بالجرامات — داخل العائلات فقط */
function toGrams(qty, unit) {
    const q = Number(qty);
    if (!Number.isFinite(q)) {return null;}
    const u = normalizeName(unit);
    if (['kg', 'كيلو', 'كيلوجرام', 'كيلو جرام', 'كيلو غرام'].includes(u)) {return q * 1000;}
    if (['g', 'جرام', 'جم', 'غرام', 'mg'].includes(u)) {return u === 'mg' ? q / 1000 : q;}
    // سوائل — كثافة ≈ 1 جم/مل (زيت ~0.92 — الفرق موسوم «تقديري» في الورقة)
    if (['لتر', 'l', 'litre', 'liter'].includes(u)) {return q * 1000;}
    if (['مل', 'ml', 'ملي', 'مليلتر'].includes(u)) {return q;}
    if (['ملعقة كبيرة', 'ملعقه كبيره', 'tbsp'].includes(u)) {return q * 15;}
    if (['ملعقة صغيرة', 'ملعقه صغيره', 'tsp'].includes(u)) {return q * 5;}
    if (['كوب', 'cup'].includes(u)) {return q * 240;}
    // العدّ والعبوات — لا وزن معتمد → لا حساب (تظهر «غير مُغطَّاة»)
    return null;
}

