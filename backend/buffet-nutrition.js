/* أسماء مرشحة إضافية عند عدم تطابقها مباشرة */
const ALIASES = [
    [/رز\s*بسمتي|ارز\s*بسمتي|بسمتي/i, 'أرز بسمتي'],
    [/رز\s*مصري|ارز\s*مصري|أرز بشاور|زربيان/i, 'أرز مصري'],
    [/مفاخ|مفروم/i, 'لحم مفروم'],
    [/دجاج/i, 'دجاج'],
    [/ضاني?|ضأن/i, 'لحم ضأن'],
    [/بقري/i, 'لحم بقري'],
    [/عدس/i, 'عدس'],
    [/حمص/i, 'حمص'],
    [/شعير/i, 'شعيرية'],
    [/مكرون[هة]?/i, 'مكرونة'],
    [/مكسرات/i, 'جوز'],
];

/* تطبيع مفاتيح الجدول مرة واحدة — التطبيع ينزع التشكيل والهمزات ويطابق */
const KEY_NORM = Object.keys(USDA).map((k) => [normalizeName(k), k]);
const DIRECT = new Map(KEY_NORM);

const atWordBoundary = (haystack, needle) =>
    haystack === needle
    || haystack.startsWith(needle + ' ')
    || haystack.includes(' ' + needle + ' ')
    || haystack.endsWith(' ' + needle);

function matchIngredient(name) {
    const n = normalizeName(name);
    if (!n) {return null;}
    if (DIRECT.has(n)) {return DIRECT.get(n);}
    let best = null;
    let bestLen = 1;
    for (const [nk, key] of KEY_NORM) {
        if (nk.length >= 2 && atWordBoundary(n, nk) && nk.length > bestLen) {best = key; bestLen = nk.length;}
    }
    if (best) {return best;}
    const bounded = (patternStr, flags) => new RegExp(`(^|\\s)(${patternStr})(\\s|$)`, flags ?? 'i');
    for (const [pattern, key] of ALIASES) {
        if (bounded(pattern.source.replace(/^\^|\$$/g, ''), pattern.flags).test(n)) {return key;}
    }
    return null;
}

