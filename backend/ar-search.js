// كل حرف من استعلام المستخدم يتوسع لعائلة الحروف المتشابهة بالنقاط — فتجد السجل
// رغم الخطأ المطبعي الشائع في لمس النقاط. تُستخدم في كل مسارات البحث بالخادم.
'use strict';

/** @type {Record<string, string>} حرف ← نمط الفئة المتشابهة */
const FAMILIES = {
    'ا': '[اأإآٱ]', 'أ': '[اأإآٱ]', 'إ': '[اأإآٱ]', 'آ': '[اأإآٱ]', 'ٱ': '[اأإآٱ]',
    'ه': '[هة]', 'ة': '[هة]',
    'ي': '[يىئ]', 'ى': '[يىئ]', 'ئ': '[يىئ]',
    'و': '[وؤ]', 'ؤ': '[وؤ]',
    'ز': '[زذ]', 'ذ': '[زذ]',
    'ر': '[رز]',
    'ص': '[صض]', 'ض': '[صض]',
    'ط': '[طظ]', 'ظ': '[طظ]',
    'س': '[سش]', 'ش': '[سش]',
    'ت': '[تث]', 'ث': '[تث]',
    'ج': '[جحخ]', 'ح': '[جحخ]', 'خ': '[جحخ]',
    'ف': '[فق]', 'ق': '[فق]',
    'ع': '[عغ]', 'غ': '[عغ]',
};
const REGEX_SPECIALS = '.*+?^${}()|[]\\/';

/**
 * @param {string} q استعلام المستخدم (أي نص).
 * @returns {string} نمط regex يقبل الحروف المتشابهة.
 */
function arFuzzyPattern(q) {
    let out = '';
    for (const ch of String(q || '')) {
        if (FAMILIES[ch]) {out += FAMILIES[ch];}
        else if (REGEX_SPECIALS.includes(ch)) {out += '\\' + ch;}
        else if (ch === ' ') {out += '\\s*';}
        else {out += ch;}
    }
    return out;
}

module.exports = { arFuzzyPattern };
