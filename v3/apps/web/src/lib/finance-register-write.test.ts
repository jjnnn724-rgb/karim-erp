import { afterEach, describe, expect, it, vi } from 'vitest';
import {
    deleteExpenseConfirm,
    deleteExpenseSuccess,
    deleteRegisterRow,
    deleteRevenue,
    deleteRevenueConfirm,
    deleteRevenueSuccess,
    EXPENSE_CATEGORIES,
    expenseFormOf,
    expenseNameOf,
    FINANCE_TEXT,
    FINANCE_WRITE_ROLES,
    financeFailureText,
    isLockedExpense,
    normalizeExpenseForm,
    normalizeRevenueForm,
    revenueFormOf,
    revenueNameOf,
    updateExpense,
    updateExpenseSuccess,
    updateRegisterRow,
    updateRevenue,
    updateRevenueSuccess,
    validateExpenseForm,
    validateRevenueForm,
} from './finance-register-write';

/**
 * كتابة الإيرادات والمصروفات — تحرس عقد `v2/data/finance-write-repo.js`:
 * الأدوار، نصوص التحقق، الحمولات، البوابات الأربع، ونصوص V2 الحرفية.
 */

vi.mock('./auth', () => ({ getAccessToken: () => 'test-token', getAppKey: () => null }));

afterEach(() => {
    vi.unstubAllGlobals();
});

function stubFetch(): ReturnType<typeof vi.fn> {
    const fetchMock = vi.fn(
        async () =>
            new Response(JSON.stringify({ ok: true }), {
                status: 200,
                headers: { 'Content-Type': 'application/json' },
            }),
    );
    vi.stubGlobal('fetch', fetchMock);
    return fetchMock;
}

describe('إيرادات ومصروفات — الأدوار والفئات', () => {
    it('أدوار الكتابة حرفيًّا: admin|manager|accountant', () => {
        expect([...FINANCE_WRITE_ROLES]).toEqual(['admin', 'manager', 'accountant']);
    });

    it('فئات المصروفات الأربع كما في V2', () => {
        expect([...EXPENSE_CATEGORIES]).toEqual(['مواد خام', 'رواتب', 'تشغيل', 'أخرى']);
    });

    it('الصف الآلي (autoGenerated) مقفول عن التعديل والحذف', () => {
        expect(isLockedExpense({ autoGenerated: true })).toBe(true);
        expect(isLockedExpense({ autoGenerated: 1 })).toBe(true);
        expect(isLockedExpense({ autoGenerated: '1' })).toBe(true);
        expect(isLockedExpense({ autoGenerated: false })).toBe(false);
        expect(isLockedExpense({})).toBe(false);
    });
});

describe('إيرادات ومصروفات — التحقق بنصوص V2', () => {
    it('نموذج إيراد فارغ: نفس ترتيب ونصوص الأخطاء', () => {
        expect(validateRevenueForm({ source: '', deptId: '', amount: '', date: '', notes: '' })).toEqual([
            { field: 'deptId', message: 'القسم مطلوب' },
            { field: 'amount', message: 'الحقل "amount" يجب أن يكون رقمًا' },
            { field: 'date', message: 'الحقل "date" يجب أن يكون تاريخًا صحيحًا' },
            { field: 'source', message: 'المصدر مطلوب' },
        ]);
    });

    it('المبلغ يجب أن يكون أكبر من صفر والحدود 50/255', () => {
        expect(validateRevenueForm({ source: 'مبيعات', deptId: 'K', amount: '0', date: '2026-11-08' })).toEqual([
            { field: 'amount', message: 'المبلغ يجب أن يكون أكبر من صفر' },
        ]);
        const longDept = 'د'.repeat(51);
        expect(
            validateRevenueForm({ source: 'مبيعات', deptId: longDept, amount: '5', date: '2026-11-08' })[0]?.message,
        ).toBe('الحقل "deptId" أطول من المسموح (الحد الأقصى 50 حرفًا)');
        expect(
            validateRevenueForm({ source: 'س'.repeat(256), deptId: 'K', amount: '5', date: '2026-11-08' })[0]?.message,
        ).toBe('الحقل "source" أطول من المسموح (الحد الأقصى 255 حرفًا)');
    });

    it('نموذج مصروف فارغ: البيان ثم الفئة الطويلة', () => {
        expect(validateExpenseForm({ desc: '', deptId: '', amount: '', date: '', category: '', notes: '' })).toEqual([
            { field: 'deptId', message: 'القسم مطلوب' },
            { field: 'amount', message: 'الحقل "amount" يجب أن يكون رقمًا' },
            { field: 'date', message: 'الحقل "date" يجب أن يكون تاريخًا صحيحًا' },
            { field: 'desc', message: 'البيان مطلوب' },
        ]);
        expect(
            validateExpenseForm({
                desc: 'كهرباء',
                deptId: 'K',
                amount: '10',
                date: '2026-11-08',
                category: 'ف'.repeat(101),
            })[0]?.message,
        ).toBe('الحقل "category" أطول من المسموح (الحد الأقصى 100 حرفًا)');
    });
});

describe('إيرادات ومصروفات — الحمولات', () => {
    it('تعديل الإيراد يرسل مفاتيح persistUpdate فقط (بلا id)', () => {
        expect(
            normalizeRevenueForm({ source: ' مبيعات ', deptId: ' K ', amount: '10.5', date: '2026-11-08', notes: ' ' }),
        ).toEqual({
            deptId: 'K',
            source: 'مبيعات',
            amount: 10.5,
            date: '2026-11-08',
            notes: '',
        });
    });

    it('تعديل المصروف يرسل desc/category وبلا autoGenerated', () => {
        const payload = normalizeExpenseForm({
            desc: 'كهرباء',
            deptId: 'K',
            amount: '40',
            date: '2026-11-08',
            category: 'تشغيل',
            notes: '',
        });
        expect(payload).toEqual({
            deptId: 'K',
            desc: 'كهرباء',
            amount: 40,
            date: '2026-11-08',
            category: 'تشغيل',
            notes: '',
        });
        expect('autoGenerated' in payload).toBe(false);
        expect('id' in payload).toBe(false);
    });

    it('قراءة النموذج من الصف تحافظ على القيم وتقصّ التاريخ', () => {
        expect(
            revenueFormOf({
                id: '9',
                source: 'مبيعات',
                deptId: 'K',
                amount: '12.00',
                date: '2026-11-08T00:00:00.000Z',
            }),
        ).toEqual({
            source: 'مبيعات',
            deptId: 'K',
            amount: '12.00',
            date: '2026-11-08',
            notes: '',
        });
        expect(
            expenseFormOf({ desc: 'غاز', deptId: 'K', category: 'تشغيل', amount: '8', date: '2026-11-07' }),
        ).toMatchObject({
            desc: 'غاز',
            category: 'تشغيل',
        });
    });
});

describe('إيرادات ومصروفات — البوابات الأربع', () => {
    it('PUT إيراد ثم DELETE إيراد على نفس المسار', async () => {
        const fetchMock = stubFetch();
        await updateRevenue('9', { source: 'مبيعات', deptId: 'K', amount: '5', date: '2026-11-08' });
        await deleteRevenue('9');
        const calls = fetchMock.mock.calls as [string, RequestInit][];
        expect(calls[0]?.[0]).toBe('/api/revenues/9');
        expect(calls[0]?.[1].method).toBe('PUT');
        expect(JSON.parse(String(calls[0]?.[1].body))).toEqual({
            deptId: 'K',
            source: 'مبيعات',
            amount: 5,
            date: '2026-11-08',
            notes: '',
        });
        expect(calls[1]?.[0]).toBe('/api/revenues/9');
        expect(calls[1]?.[1].method).toBe('DELETE');
    });

    it('PUT مصروف ثم DELETE مصروف', async () => {
        const fetchMock = stubFetch();
        await updateExpense('4', { desc: 'كهرباء', deptId: 'K', amount: '40', date: '2026-11-08', category: 'تشغيل' });
        await deleteRegisterRow('expenses', '4');
        const calls = fetchMock.mock.calls as [string, RequestInit][];
        expect(calls[0]?.[0]).toBe('/api/expenses/4');
        expect(JSON.parse(String(calls[0]?.[1].body)).category).toBe('تشغيل');
        expect(calls[1]?.[1].method).toBe('DELETE');
    });

    it('البوابة الموحّدة توجّه حسب النوع', async () => {
        const fetchMock = stubFetch();
        await updateRegisterRow('revenues', '1', {
            source: 'أ',
            deptId: 'K',
            amount: '1',
            date: '2026-11-08',
            notes: '',
        });
        await deleteRegisterRow('revenues', '1');
        const urls = (fetchMock.mock.calls as [string, RequestInit][]).map((call) => call[0]);
        expect(urls).toEqual(['/api/revenues/1', '/api/revenues/1']);
    });
});

describe('إيرادات ومصروفات — نصوص V2 الحرفية', () => {
    it('رسائل النجاح', () => {
        expect(updateRevenueSuccess('مبيعات')).toBe('تم تعديل إيراد «مبيعات»');
        expect(updateExpenseSuccess('كهرباء')).toBe('تم تعديل مصروف «كهرباء»');
        expect(deleteRevenueSuccess('مبيعات', '9')).toBe('تم حذف إيراد «مبيعات»');
        expect(deleteExpenseSuccess('', '4')).toBe('تم حذف مصروف «#4»');
    });

    it('نصوص تأكيد الحذف بلا رجعة', () => {
        expect(deleteRevenueConfirm('مبيعات', '9')).toBe('حذف إيراد «مبيعات»؟ لا رجعة بعد الحذف.');
        expect(deleteRevenueConfirm('', '9')).toBe('حذف إيراد «#9»؟ لا رجعة بعد الحذف.');
        expect(deleteExpenseConfirm('كهرباء', '4')).toBe('حذف مصروف «كهرباء»؟ لا رجعة بعد الحذف.');
    });

    it('رسالة فشل العملية تسبق رسالة الخادم', () => {
        expect(financeFailureText('قيد مرحّل لا يُحذف')).toBe('فشلت العملية: قيد مرحّل لا يُحذف');
        expect(FINANCE_TEXT.saveFailed).toBe('فشل الحفظ');
    });

    it('أسماء الصفوف من المصدر والبيان', () => {
        expect(revenueNameOf({ source: ' مبيعات ' })).toBe('مبيعات');
        expect(expenseNameOf({ desc: 'كهرباء' })).toBe('كهرباء');
        expect(revenueNameOf({})).toBe('');
    });
});
