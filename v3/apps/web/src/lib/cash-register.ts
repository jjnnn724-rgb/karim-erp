export interface CashRegisterFilters {
    from?: string;
    to?: string;
    type?: string;
    dept?: string;
    q?: string;
    limit?: number;
    offset?: number;
    sort?: string;
    dir?: 'asc' | 'desc';
}

export async function fetchCashRegister(
    filters: CashRegisterFilters = {},
    signal?: AbortSignal,
): Promise<CashRegisterResponse> {
    const params = new URLSearchParams();
    for (const [key, value] of Object.entries(filters)) {
        if (value !== undefined && value !== null && String(value) !== '') {
            params.set(key, String(value));
        }
    }
    const query = params.toString();
    return fetchJson(
        cashRegisterResponseSchema,
        `/api/expense-register${query ? `?${query}` : ''}`,
        getAccessToken(),
        signal ? { signal } : {},
    );
}

export async function fetchExpenseVoucher(id: string, signal?: AbortSignal): Promise<ExpenseVoucher> {
    return fetchJson(
        expenseVoucherSchema,
        `/api/expense-register/voucher/${encodeURIComponent(id)}`,
        getAccessToken(),
        signal ? { signal } : {},
    );
}

/** كشف السجل A4 من الخادم بنفس مرشّحات الشاشة (سقف الورقة 400 حركة). */
export async function fetchRegisterHtml(filters: CashRegisterFilters = {}): Promise<string> {
    const params = new URLSearchParams();
    for (const key of ['from', 'to', 'type', 'dept', 'q'] as const) {
        const value = filters[key];
        if (value) {
            params.set(key, String(value));
        }
    }
    params.set('limit', '400');
    return fetchText(`/api/expense-register/html?${params.toString()}`, getAccessToken());
}

/** ورقة إذن الصرف A4 من الخادم. */
export async function fetchVoucherHtml(id: string): Promise<string> {
    return fetchText(
        `/api/expense-register/voucher/${encodeURIComponent(id)}/html`,
        getAccessToken(),
    );
}

