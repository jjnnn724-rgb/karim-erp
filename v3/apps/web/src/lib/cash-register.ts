/* ── التقرير المفصل بأصناف مختارة ───────────────────────────────────────── */

export const MULTI_REPORT_LIMIT = 6;
/** سقف صفوف الفترة التي يفحصها التقرير — يُعلَن للمستخدم إن لم تغطِّ الكل. */
export const MULTI_REPORT_SCAN = 400;

/** مدخلات التقرير: فاصلة عربية أو لاتينية، وحدٌّ أقصى ٦ أصناف (نفس القديم). */
export function parseReportTokens(value: string): string[] {
    return String(value ?? '')
        .split(/[,،]/)
        .map((token) => token.replace(/[%_;()]/g, ' ').trim())
        .filter(Boolean)
        .slice(0, MULTI_REPORT_LIMIT);
}

export interface MultiReportOptions {
    from: string;
    to: string;
    tokens: readonly string[];
    rows: readonly CashRegisterRow[];
    totalCount: number;
    currency: string;
    generatedAt?: Date;
}

function escapeHtml(value: unknown): string {
    return String(value ?? '')
        .replace(/&/g, '&amp;')
        .replace(/</g, '&lt;')
        .replace(/>/g, '&gt;')
        .replace(/"/g, '&quot;')
        .replace(/'/g, '&#39;');
}

/**
 * ورقة «تقرير مفصل»: قسمٌ لكل صنف بحث عن حركات الفترة التي يطابق بيانها أو
 * قسمها المصطلح، ثم مجموع القسم والمجموع العام والأصناف التي لم تُطابَق.
 * الفحص على صفوف الفترة كما أعلنها الخادم (`totals.count`)، ويُصرَّح إن لم
 * يشمل الفحص كل الصفوف — لا تقرير يدّعي الشمول وهو ناقص.
 */
/** طابع زمني لاتيني الأرقام (`dd/mm/yyyy hh:mm`) — لا أرقام هندية وسط مستند لاتيني. */
function reportStamp(date: Date): string {
    const pad = (value: number): string => String(value).padStart(2, '0');
    return `${pad(date.getDate())}/${pad(date.getMonth() + 1)}/${date.getFullYear()} ${pad(date.getHours())}:${pad(date.getMinutes())}`;
}

export function multiReportHtml(options: MultiReportOptions): string {
    const { from, to, tokens, rows, totalCount, currency } = options;
    const generatedAt = reportStamp(options.generatedAt ?? new Date());
    const needle = (value: unknown): string => String(value ?? '').toLocaleLowerCase();
    const sections: string[] = [];
    const missing: string[] = [];
    let grandCount = 0;
    let grandAmount = 0;

    for (const token of tokens) {
        const query = needle(token);
        const hits = rows.filter(
            (row) => needle(row.desc).includes(query) || needle(row.request_dept ?? row.deptId).includes(query),
        );
        if (!hits.length) {
            missing.push(token);
            continue;
        }
        const total = hits.reduce((sum, row) => sum + (Number(row.amount) || 0), 0);
        grandCount += hits.length;
        grandAmount += total;
        const body = hits
            .map(
                (row, index) =>
                    `<tr><td class="c">${index + 1}</td><td class="c n">${escapeHtml(String(row.date ?? '').slice(0, 10))}</td>` +
                    `<td class="c n">${escapeHtml(voucherRef(row.request_id).short || '—')}</td>` +
                    `<td>${escapeHtml(row.desc || '—')}</td>` +
                    `<td>${escapeHtml(row.request_dept ?? row.deptId ?? '—')}</td>` +
                    `<td class="c n"><b>${escapeHtml(moneyText(row.amount, currency))}</b></td></tr>`,
            )
            .join('');
        sections.push(
            `<h3 class="sec">صنف/بحث: ${escapeHtml(token)} — ${escapeHtml(intText(hits.length))} حركة · ` +
                `${escapeHtml(moneyText(total, currency))}</h3>` +
                '<table><thead><tr><th>#</th><th>التاريخ</th><th>الإذن</th><th>البيان</th><th>القسم</th><th>المبلغ</th></tr></thead>' +
                `<tbody>${body}</tbody>` +
                `<tfoot><tr><td colspan="5">مجموع ${escapeHtml(token)}</td>` +
                `<td class="c n"><b>${escapeHtml(moneyText(total, currency))}</b></td></tr></tfoot></table>`,
        );
    }

    const scanNote =
        totalCount > rows.length
            ? `<p class="note">روعي أول ${escapeHtml(intText(rows.length))} من ${escapeHtml(
                  intText(totalCount),
              )} حركة في الفترة — ضيّق المدى لدقة أشمل.</p>`
            : '';

    return `<!DOCTYPE html><html dir="rtl" lang="ar"><head><meta charset="UTF-8">
<meta name="viewport" content="width=device-width, initial-scale=1.0">
<title>تقرير مفصل — سجلّ الصرف</title>
<style>
body{font-family:'IBM Plex Sans Arabic','Tajawal',Tahoma,Arial,sans-serif;color:#111;background:#fff;margin:0;padding:28px;direction:rtl}
.sheet{max-width:960px;margin:auto}
.head{text-align:center;border-bottom:3px solid #0f5b46;padding-bottom:14px;margin-bottom:16px}
.head h1{margin:0 0 6px;color:#0f5b46;font-size:22px}.head p{margin:3px 0;color:#555;font-size:13px}
h3.sec{font-size:14px;color:#0a3d2f;border-bottom:2px solid #eaf3ee;padding-bottom:5px;margin:18px 0 8px}
table{width:100%;border-collapse:collapse;margin-bottom:10px}th,td{border:1px solid #ccc;padding:6px;text-align:right;font-size:12px}
th{background:#eaf3ee;color:#0a3d2f}td.c,th.c{text-align:center}td.n{direction:ltr;unicode-bidi:embed}
.note{border:1px solid #e5d9b5;background:#fdf9ee;border-radius:8px;padding:8px 12px;font-size:12px;color:#6b5620}
.controls{text-align:center;margin-bottom:18px}.controls button{border:0;border-radius:7px;padding:10px 24px;margin:0 5px;font:inherit;cursor:pointer;background:#0f5b46;color:#fff}
.controls button.secondary{background:#555}
@media print{body{padding:0}.controls{display:none!important}@page{size:A4;margin:11mm}}
</style></head><body>
<div class="controls"><button type="button" data-report-print>طباعة</button><button type="button" class="secondary" data-report-close>إغلاق</button></div>
<main class="sheet"><header class="head"><h1>تقرير مفصل — سجلّ الصرف</h1>
<p>الفترة: ${escapeHtml(from || 'البداية')} ← ${escapeHtml(to || 'اليوم')} — تاريخ التقرير: ${escapeHtml(generatedAt)}</p>
<p>الأصناف المطلوبة: ${escapeHtml(tokens.join('، '))}</p></header>
${scanNote}
${sections.length ? sections.join('') : '<p class="sec">لا حركات مطابقة لما كتبته في هذه الفترة.</p>'}
${missing.length ? `<p class="sec">لم تطابقها الحركات: ${escapeHtml(missing.join('، '))}</p>` : ''}
${
    sections.length
        ? `<p class="sec"><b>مجموع التقرير:</b> ${escapeHtml(intText(grandCount))} حركة · ${escapeHtml(
              moneyText(grandAmount, currency),
          )}</p>`
        : ''
}
</main></body></html>`;
}
