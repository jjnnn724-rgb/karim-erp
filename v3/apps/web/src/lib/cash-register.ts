export type StatusTone = 'success' | 'warning' | 'danger' | 'neutral';

/** درجة اللون دلالةٌ ثانوية: النصّ العربي للحالة هو الحامل للمعنى. */
export function dispatchStatusTone(value: string | null | undefined): StatusTone {
    switch (String(value ?? '')) {
        case 'approved':
        case 'received':
            return 'success';
        case 'pending':
        case 'chef_approved':
        case 'partially_received':
            return 'warning';
        case 'rejected':
            return 'danger';
        default:
            return 'neutral';
    }
}

/** رقم الإذن مختصرًا مع بقاء كامله للنسخ (نفس `voucherRef` في القديم). */
export function voucherRef(id: string | number | null | undefined): { full: string; short: string } {
    const full = String(id ?? '');
    if (!full) {
        return { full: '', short: '' };
    }
    return { full, short: full.length > 8 ? `…${full.slice(-6)}` : full };
}

/**
 * البيان المولَّد آليًا يبدأ بـ«النوع - الصنف»؛ يُفصل للعرض فقط، ولو خالف
 * القالب يُعرض كاملًا كما هو (نفس `splitDesc` في القديم).
 */
export function splitDesc(desc: string | null | undefined, label: string): { lead: string; rest: string } {
    const text = String(desc ?? '');
    if (!text) {
        return { lead: '', rest: '' };
    }
    const lead = String(label ?? '');
    if (lead && text.startsWith(`${lead} - `)) {
        return { lead, rest: text.slice(lead.length + 3) };
    }
    return { lead: '', rest: text };
}

function amountText(value: unknown): string {
    if (value === null || value === undefined || value === '') {
        return '—';
    }
    if (typeof value === 'string') {
        const trimmed = value.trim();
        if (/^-?\d+(?:\.\d{1,2})?$/.test(trimmed)) {
            return formatMoney(trimmed);
        }
    }
    const parsed = typeof value === 'number' ? value : Number(String(value ?? '').replaceAll(',', ''));
    if (!Number.isFinite(parsed)) {
        return '—';
    }
    return parsed.toLocaleString('en-US', { minimumFractionDigits: 2, maximumFractionDigits: 2 });
}

/** مبلغ للعرض: النصّ كما هو للـNUMERIC، والوحدة تأتي من الخادم لا من نصٍّ ثابت. */
export function moneyText(value: unknown, currency = ''): string {
    const unit = String(currency ?? '').trim();
    const amount = amountText(value);
    return unit ? `${amount} ${unit}` : amount;
}

export function intText(value: unknown): string {
    const parsed = Number(value ?? 0);
    return formatInt(Number.isFinite(parsed) ? parsed : 0);
}

/** كمية بثلاث خانات كحد أقصى — لسلسلة الأيام (نفس `formatQty` في القديم). */
export function qtyText(value: unknown): string {
    const parsed = Number(value ?? 0);
    if (!Number.isFinite(parsed)) {
        return '0';
    }
    return parsed.toLocaleString('en-US', { maximumFractionDigits: 3 });
}

