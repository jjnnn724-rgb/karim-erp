import { addMoney, roundHalfUp } from '@karim/shared';
import { z } from 'zod';
import { fetchJson } from './api';
import { getAccessToken } from './auth';

/**
 * سجلات الإيرادات والمصروفات — قراءة من المسارات القديمة `/api/revenues`
 * و`/api/expenses` بنفس عقد الشاشة القديمة (`finance-repo.js`):
 * `?page=&limit=&sort=id&order=desc&v2_period=month` ثم `{data, pagination}`.
 *
 * طبقة البيانات هنا **لا تكتب** ولا تعيد حساب أي مبلغ: العرض والتجميع
 * النصّي فقط (ADR-04). ترحيل هذه المسارات إلى `/api/v3` لاحقًا لا يغيّر
 * هذه الواجهة.
 */

const moneyValue = z.union([z.string(), z.number()]).transform((value) => String(value));

const rowBase = {
    id: z.union([z.string(), z.number()]).transform((value) => String(value)),
    deptId: z.string().nullable().optional(),
    amount: moneyValue,
    date: z.string(),
    notes: z.string().nullable().optional(),
};

export const revenueRowSchema = z
    .object({
        ...rowBase,
        source: z.string().nullable().optional(),
    })
    .passthrough();

export const expenseRowSchema = z
    .object({
        ...rowBase,
        desc: z.string().nullable().optional(),
        category: z.string().nullable().optional(),
        adjustmentType: z.string().nullable().optional(),
        autoGenerated: z.boolean().nullable().optional(),
    })
    .passthrough();

export type RevenueRow = z.infer<typeof revenueRowSchema>;
export type ExpenseRow = z.infer<typeof expenseRowSchema>;
export type RegisterRow = RevenueRow | ExpenseRow;

const paginationSchema = z
    .object({
        total: z.number().optional(),
        totalPages: z.number().optional(),
    })
    .passthrough();

const pageSchema = (row: z.ZodType<RegisterRow>) =>
    z
        .object({
            data: z.array(row),
            pagination: paginationSchema.optional(),
        })
        .passthrough();

export const departmentSchema = z
    .object({
        id: z.union([z.string(), z.number()]).optional(),
        code: z.string(),
        name: z.string(),
        parent_code: z.string().nullable().optional(),
        icon: z.string().nullable().optional(),
        color: z.string().nullable().optional(),
    })
    .passthrough();

export type Department = z.infer<typeof departmentSchema>;

const departmentsPageSchema = z.object({ data: z.array(departmentSchema) }).passthrough();

const settingsSchema = z.object({ currency: z.string().nullable().optional() }).passthrough();

export type RegisterEntity = 'revenues' | 'expenses';

const SCHEMAS: Record<RegisterEntity, z.ZodType<RegisterRow>> = {
    revenues: revenueRowSchema,
    expenses: expenseRowSchema,
};

const PAGE_SIZE = 1000;
const MAX_PAGES = 200;

/**
 * يمشي صفحات الشهر الحالي كما كان القديم (`WALK_ALL_PAGES=200`) لأن
 * المجاميع يجب أن تكون كاملة؛ العدد الواقعي اليوم 7 صفحات للإيرادات.
 */
export async function fetchRegister(entity: RegisterEntity, signal?: AbortSignal): Promise<RegisterRow[]> {
    const rows: RegisterRow[] = [];
    for (let page = 1; page <= MAX_PAGES; page += 1) {
        const body = await fetchJson(
            pageSchema(SCHEMAS[entity]),
            `/api/${entity}?page=${String(page)}&limit=${String(PAGE_SIZE)}&sort=id&order=desc&v2_period=month`,
            getAccessToken(),
            signal ? { signal } : {},
        );
        rows.push(...body.data);
        const totalPages = body.pagination?.totalPages ?? 0;
        if (body.data.length < PAGE_SIZE || (totalPages > 0 && page >= totalPages)) {
            break;
        }
    }
    return rows;
}

export async function fetchDepartments(signal?: AbortSignal): Promise<Department[]> {
    const body = await fetchJson(
        departmentsPageSchema,
        '/api/departments?page=1&limit=1000&sort=id&order=desc',
        getAccessToken(),
        signal ? { signal } : {},
    );
    return body.data;
}

export async function fetchCurrency(signal?: AbortSignal): Promise<string> {
    const body = await fetchJson(
        settingsSchema,
        '/api/settings/main_settings',
        getAccessToken(),
        signal ? { signal } : {},
    );
    return body.currency ?? '';
}

