/** مبلغ من الخادم (نصّ NUMERIC) → نصّ منتهٍ بحانتين، بلا Float. */
export function normalizeAmount(value: string): string {
    return roundHalfUp(value, 2);
}

export function sumAmounts(rows: readonly RegisterRow[]): string {
    return rows.reduce((sum, row) => addMoney(sum, normalizeAmount(row.amount)), '0.00');
}

/** اليوم في الرياض (UTC+3 بلا توقيت صيفي) — نفس مصدر القديم. */
export function riyadhToday(now = new Date()): string {
    return new Date(now.getTime() + 3 * 60 * 60 * 1000).toISOString().slice(0, 10);
}

export function firstOfMonth(today = riyadhToday()): string {
    return `${today.slice(0, 7)}-01`;
}

/** ملاحظة الاستيراد الآلي تُعرض بالعربية بدل `key=value` — نفس القديم حرفيًا. */
export function noteText(raw: string | null | undefined): string {
    const text = String(raw ?? '').trim();
    if (!text.startsWith('[AUTO:YARASOFT]')) {
        return text;
    }
    const facts = text
        .split('|')
        .map((part) => part.trim())
        .filter(Boolean)
        .slice(1)
        .map((part) => {
            const match = /^([a-z_]+)=(.*)$/i.exec(part);
            if (!match) {
                return part;
            }
            const [, key = '', value = ''] = match;
            if (key.toLowerCase() === 'invoice') {
                return `فاتورة ${value.trim()}`;
            }
            if (key.toLowerCase() === 'sec') {
                return `الجهة: ${value.trim()}`;
            }
            if (key.toLowerCase() === 'items') {
                return `الأصناف: ${value.trim()}`;
            }
            return value.trim();
        });
    return ['مبيعات الكاشير', ...facts].join(' · ');
}

const STOCK_TYPES = [
    'dispatch',
    'dispatch_return',
    'receipt',
    'stock_transfer',
    'inventory_transfer',
    'kitchen_return',
];

export function expenseKind(row: ExpenseRow): 'count' | 'return' | 'stock' | 'auto' | 'manual' {
    const type = String(row.adjustmentType ?? '').toLowerCase();
    if (type === 'count_correction') {
        return 'count';
    }
    if (STOCK_TYPES.includes(type)) {
        return Number(row.amount) < 0 ? 'return' : 'stock';
    }
    return row.autoGenerated ? 'auto' : 'manual';
}

