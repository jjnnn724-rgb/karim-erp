/** الأقسام القابلة للاختيار — التشغيلية وحدها (بلا قناة بيع أو مرآة خارجية). */
export function selectableDepts(analysis: CostAnalysis | undefined): { code: string; name: string }[] {
    return (analysis?.rows ?? [])
        .filter((row) => !row.channel && !row.external)
        .map((row) => ({ code: String(row.code ?? ''), name: String(row.name ?? row.code ?? '') }))
        .filter((row) => row.code.length > 0)
        .sort((a, b) => a.name.localeCompare(b.name, 'ar'));
}

/** أعلى الأقسام تكلفةً — العرض مرتّب على ما وصل فقط. */
export function topCostRows(analysis: CostAnalysis | undefined, limit = 8): CostRow[] {
    return [...(analysis?.rows ?? [])]
        .filter((row) => !row.channel)
        .sort((a, b) => Number(b.exp ?? 0) - Number(a.exp ?? 0))
        .slice(0, limit);
}
