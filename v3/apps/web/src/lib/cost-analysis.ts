import { z } from 'zod';
import { fetchJson } from './api';
import { getAccessToken } from './auth';

/**
 * تحليل التكاليف — عقد V3 من `finance-routes`:
 *
 *   GET /api/finance/cost-analysis?from&to →
 *     {rows:[{code,name,parent,channel,external,rev,exp,profit,costRatio,
 *             materials,transfers,countAdj,operating,rowCount,own{...}}],
 *      totals:{rev,mat,trn,cnt,ops,exp,avgCost},
 *      attribution:{links[],channelRevenue[]}, flow, previous, period{from,to}}
 *
 *   GET /api/finance/cost-analysis/dept?code&from&to →
 *     {code,from,to,buckets{materials,transfers,countAdj,operating},total,
 *      items:[{id,deptCode,deptName,description,amount,date,category,
 *              adjustmentType,autoGenerated,notes}],period}
 *
 * كل الأرقام من الخادم كما هي؛ `costRatio` و`profit` تُعرضان ولا تُعاد
 * حسابتهما. حد البنود 800 في تفاصيل القسم (نافذة الخادم).
 */

const numLike = z.union([z.string(), z.number()]).nullable().optional();
const text = z.string().nullable().optional();
const idValue = z.union([z.string(), z.number()]).transform((value) => String(value));

const ownSchema = z
    .object({
        rev: numLike,
        exp: numLike,
        profit: numLike,
        costRatio: numLike,
        materials: numLike,
        transfers: numLike,
        countAdj: numLike,
        operating: numLike,
        rowCount: numLike,
    })
    .passthrough();

const costRowSchema = z
    .object({
        code: text,
        name: text,
        parent: z.union([z.string(), z.null()]).optional(),
        channel: z.union([z.boolean(), z.number()]).nullable().optional(),
        external: z.union([z.boolean(), z.number()]).nullable().optional(),
        rev: numLike,
        exp: numLike,
        profit: numLike,
        costRatio: numLike,
        materials: numLike,
        transfers: numLike,
        countAdj: numLike,
        operating: numLike,
        total: numLike,
        rowCount: numLike,
        own: ownSchema.optional(),
    })
    .passthrough();

const totalsSchema = z
    .object({
        rev: numLike,
        mat: numLike,
        trn: numLike,
        cnt: numLike,
        ops: numLike,
        exp: numLike,
        avgCost: numLike,
    })
    .passthrough();

export const costAnalysisSchema = z
    .object({
        rows: z.array(costRowSchema).optional(),
        totals: totalsSchema.optional(),
        categories: z.array(z.unknown()).optional(),
        attribution: z
            .object({
                links: z.array(z.object({ cashierNo: text, dept: text, primary: z.unknown() }).passthrough()).optional(),
                channelRevenue: z.array(z.object({ code: text, revenue: numLike }).passthrough()).optional(),
            })
            .passthrough()
            .optional(),
        period: z.object({ from: text, to: text }).passthrough().optional(),
        previous: z.unknown().optional(),
    })
    .passthrough();

export type CostAnalysis = z.infer<typeof costAnalysisSchema>;
export type CostRow = z.infer<typeof costRowSchema>;

export const deptCostDetailSchema = z
    .object({
        code: text,
        buckets: z
            .object({
                materials: numLike,
                transfers: numLike,
                countAdj: numLike,
                operating: numLike,
            })
            .passthrough()
            .optional(),
        total: numLike,
        items: z
            .array(
                z
                    .object({
                        id: idValue,
                        deptCode: text,
                        deptName: text,
                        description: text,
                        amount: numLike,
                        date: text,
                        category: text,
                        adjustmentType: text,
                        autoGenerated: z.union([z.boolean(), z.number()]).nullable().optional(),
                        notes: text,
                    })
                    .passthrough(),
            )
            .optional(),
        period: z.object({ from: text, to: text }).passthrough().optional(),
    })
    .passthrough();

export type DeptCostDetail = z.infer<typeof deptCostDetailSchema>;

export async function fetchCostAnalysis(from: string, to: string, signal?: AbortSignal): Promise<CostAnalysis> {
    const query = from && to ? `?from=${encodeURIComponent(from)}&to=${encodeURIComponent(to)}` : '';
    return fetchJson(
        costAnalysisSchema,
        `/api/finance/cost-analysis${query}`,
        getAccessToken(),
        signal ? { signal } : {},
    );
}

export async function fetchDeptCostDetail(
    code: string,
    from: string,
    to: string,
    signal?: AbortSignal,
): Promise<DeptCostDetail> {
    const range = from && to ? `&from=${encodeURIComponent(from)}&to=${encodeURIComponent(to)}` : '';
    return fetchJson(
        deptCostDetailSchema,
        `/api/finance/cost-analysis/dept?code=${encodeURIComponent(code)}${range}`,
        getAccessToken(),
        signal ? { signal } : {},
    );
}

