import { QueryClient, QueryClientProvider } from '@tanstack/react-query';
import { render, screen } from '@testing-library/react';
import { afterEach, describe, expect, it, vi } from 'vitest';
import { ToastProvider } from '../ui/Toast';
import { CostCenter } from './CostCenter';

function json(body: unknown, status = 200): Response {
    return new Response(JSON.stringify(body), {
        status,
        headers: { 'Content-Type': 'application/json' },
    });
}

function renderScreen() {
    const client = new QueryClient({ defaultOptions: { queries: { retry: false } } });
    return render(
        <QueryClientProvider client={client}>
            <ToastProvider>
                <CostCenter />
            </ToastProvider>
        </QueryClientProvider>,
    );
}

afterEach(() => {
    vi.unstubAllGlobals();
});

describe('مركز التكلفة', () => {
    it('يختار أول قسم تشغيلي ويعرض بنوده وأوعيته', async () => {
        vi.stubGlobal(
            'fetch',
            vi.fn(async (input: RequestInfo | URL) => {
                const url = typeof input === 'string' ? input : input.toString();
                if (url.includes('/api/finance/cost-analysis/dept')) {
                    return json({
                        code: 'KITCHEN',
                        buckets: { materials: 900, transfers: 100, countAdj: 50, operating: 150 },
                        total: 1200,
                        items: [
                            {
                                id: 7,
                                deptCode: 'KITCHEN',
                                deptName: 'المشويات',
                                description: 'صرف لحم',
                                amount: 900,
                                date: '2026-11-05',
                                category: 'مواد',
                                adjustmentType: 'dispatch',
                                autoGenerated: true,
                            },
                        ],
                        period: { from: '2026-11-01', to: '2026-11-07' },
                    });
                }
                if (url.includes('/api/finance/cost-analysis')) {
                    return json({
                        rows: [
                            { code: 'SALES', name: 'المبيعات', channel: true, exp: 0 },
                            { code: 'KITCHEN', name: 'المطبخ', channel: false, exp: 1200 },
                        ],
                        totals: { rev: 5000, exp: 1200 },
                    });
                }
                return json({ error: 'NOT_FOUND', message: 'مسار غير معروف' }, 404);
            }),
        );

        renderScreen();

        expect(await screen.findByText('إجمالي القسم')).toBeTruthy();
        expect(screen.getAllByText('1,200.00 SAR').length).toBeGreaterThan(0);
        expect(screen.getByText('صرف لحم')).toBeTruthy();
        expect(screen.getByText('صرف مخزني')).toBeTruthy();
        expect(screen.getByText('المشويات')).toBeTruthy();
    });
});
