import { QueryClient, QueryClientProvider } from '@tanstack/react-query';
import { fireEvent, render, screen, waitFor, within } from '@testing-library/react';
import { afterEach, describe, expect, it, vi } from 'vitest';
import { ToastProvider } from '../ui/Toast';
import { Departments } from './Departments';

/**
 * السجل يجمع صفوف الشهر المحمّلة لكل قسم (صفوف القسم نفسه، لا الأبناء)،
 * ويطوي الأقسام المرآتية `ys_*` عرضًا فقط. المؤشرات — كالقديم حرفيًا —
 * تجمع كل صفوف الشهر بما فيها المرآة وغير المسندة.
 */

const departments = [
    { id: 1, code: 'K01', name: 'المطبخ', parent_code: null },
    { id: 2, code: 'K02', name: 'الحلويات', parent_code: 'K01' },
    { id: 3, code: 'ys_cc_1', name: 'مبيعات كاشير 1', parent_code: null },
];

const revenues = {
    data: [
        { id: 1, deptId: 'K01', amount: '1000.50', date: '2026-11-01', source: 'بيع' },
        { id: 2, deptId: 'K02', amount: '250', date: '2026-11-02', source: 'بيع' },
        { id: 3, deptId: 'ys_cc_1', amount: '9999', date: '2026-11-02', source: 'كاشير' },
    ],
    pagination: { totalPages: 1 },
};

const expenses = {
    data: [
        {
            id: 1,
            deptId: 'K01',
            desc: 'خضار',
            amount: '400.25',
            date: '2026-11-03',
            notes: null,
            autoGenerated: false,
            adjustmentType: 'dispatch',
        },
    ],
    pagination: { totalPages: 1 },
};

function json(body: unknown, status = 200): Response {
    return new Response(JSON.stringify(body), {
        status,
        headers: { 'Content-Type': 'application/json' },
    });
}

function stubFetch(fail = false): void {
    vi.stubGlobal(
        'fetch',
        vi.fn(async (url: string) => {
            if (fail) {
                return json({ error: 'FAILED', message: 'تعذر جلب الأقسام' }, 500);
            }
            const href = String(url);
            if (href.includes('/api/departments')) {
                return json({ data: departments, pagination: { totalPages: 1 } });
            }
            if (href.includes('/api/revenues')) {
                return json(revenues);
            }
            if (href.includes('/api/expenses')) {
                return json(expenses);
            }
            if (href.includes('/api/settings/main_settings')) {
                return json({ currency: 'SAR' });
            }
            return json({ error: 'NOT_FOUND', message: 'مسار غير معروف' }, 404);
        }),
    );
}

function renderScreen() {
    const client = new QueryClient({ defaultOptions: { queries: { retry: false } } });
    return render(
        <QueryClientProvider client={client}>
            <ToastProvider>
                <Departments />
            </ToastProvider>
        </QueryClientProvider>,
    );
}

function dataRows(): HTMLElement[] {
    return screen.getAllByRole('row').slice(1) as HTMLElement[];
}

afterEach(() => {
    vi.unstubAllGlobals();
});

describe('سجل الأقسام', () => {
    it('يجمع الشهر لكل قسم وتجمع المؤشرات كل الصفوف كالقديم', async () => {
        stubFetch();
        renderScreen();

        await waitFor(() => {
            expect(screen.getByRole('table')).toBeTruthy();
        });

        expect(screen.getByRole('heading', { level: 1 }).textContent).toContain('الأقسام');
        expect(screen.getByText('2')).toBeTruthy();
        expect(screen.getByText('11,249.50 SAR')).toBeTruthy();
        expect(screen.getByText('400.25 SAR')).toBeTruthy();
        expect(screen.getByText('10,849.25 SAR')).toBeTruthy();

        expect(dataRows()).toHaveLength(2);
        const row = screen.getByText('المطبخ').closest('tr') as HTMLElement;
        expect(within(row).getByText('1,000.50')).toBeTruthy();
        expect(within(row).getByText('400.25')).toBeTruthy();
        expect(within(row).getByText('600.25')).toBeTruthy();
        expect(within(row).getByText('40.0%')).toBeTruthy();
    });

    it('يطوي أقسام المرآة ويعيدها بالمفتاح ويبحث بالاسم والأب', async () => {
        stubFetch();
        renderScreen();
        await waitFor(() => {
            expect(screen.getByRole('table')).toBeTruthy();
        });

        expect(screen.queryByText('مبيعات كاشير 1')).toBeNull();

        fireEvent.click(screen.getByLabelText('إظهار أقسام المرآة (ys_)'));
        await waitFor(() => {
            expect(dataRows()).toHaveLength(3);
        });
        expect(screen.getByText('مبيعات كاشير 1')).toBeTruthy();

        fireEvent.click(screen.getByLabelText('إظهار أقسام المرآة (ys_)'));
        fireEvent.change(screen.getByLabelText('بحث'), { target: { value: 'المطبخ' } });
        await waitFor(() => {
            expect(dataRows()).toHaveLength(2);
        });
        expect(screen.getByText('تحت المطبخ')).toBeTruthy();
    });

    it('يعرض الفراغ حين لا يطابق البحث شيئًا', async () => {
        stubFetch();
        renderScreen();
        await waitFor(() => {
            expect(screen.getByRole('table')).toBeTruthy();
        });

        fireEvent.change(screen.getByLabelText('بحث'), { target: { value: 'لا-يوجد' } });

        await waitFor(() => {
            expect(screen.getByText('لا أقسام')).toBeTruthy();
        });
        expect(screen.queryByRole('table')).toBeNull();
    });

    it('يعرض خطأً قابلًا لإعادة المحاولة', async () => {
        stubFetch(true);
        renderScreen();

        await waitFor(() => {
            expect(screen.getByRole('alert')).toBeTruthy();
        });
        expect(screen.getByRole('button', { name: 'إعادة المحاولة' })).toBeTruthy();
    });
});
