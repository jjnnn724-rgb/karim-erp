import { QueryClient, QueryClientProvider } from '@tanstack/react-query';
import { fireEvent, render, screen, waitFor, within } from '@testing-library/react';
import { afterEach, describe, expect, it, vi } from 'vitest';
import { ConfirmProvider } from '../components/ConfirmProvider';
import { riyadhToday } from '../lib/finance';
import { ToastProvider } from '../ui/Toast';
import { EXPENSES_CONFIG, FinanceRegister, REVENUES_CONFIG } from './FinanceRegister';

/**
 * السجل المالي يعرض ما يعيده الخادم حرفيًا (ADR-04)، والترشيح والبحث
 * والفرز كلها عميلة — فتُثبَّت هنا على بيانات صغيرة صريحة.
 */

const TODAY = riyadhToday();

const revenueRows = [
    {
        id: 2,
        amount: '250.25',
        date: TODAY,
        deptId: '20',
        source: 'مبيعات صالة',
        notes: '[AUTO:YARASOFT]|invoice=88|items=قهوة',
    },
    { id: 1, amount: '1000.50', date: TODAY, deptId: '10', source: 'مبيعات كاشير', notes: null },
];

const expenseRows = [
    {
        id: 5,
        amount: '75.00',
        date: TODAY,
        deptId: '10',
        desc: 'مشتريات',
        adjustmentType: 'count_correction',
        autoGenerated: false,
    },
    {
        id: 4,
        amount: '120.00',
        date: TODAY,
        deptId: '',
        desc: 'صرف للمخزن',
        adjustmentType: 'dispatch',
        autoGenerated: true,
    },
];

function json(body: unknown, status = 200): Response {
    return new Response(JSON.stringify(body), {
        status,
        headers: { 'Content-Type': 'application/json' },
    });
}

function stubFetch(options: { revenue?: unknown; expense?: unknown; status?: number } = {}): void {
    vi.stubGlobal(
        'fetch',
        vi.fn(async (url: string) => {
            const href = String(url);
            if (options.status && options.status >= 400) {
                return json({ error: 'FAILED', message: 'تعذر جلب السجلات' }, options.status);
            }
            if (href.includes('/api/revenues')) {
                return json(options.revenue ?? { data: revenueRows, pagination: { total: 2, totalPages: 1 } });
            }
            if (href.includes('/api/expenses')) {
                return json(options.expense ?? { data: expenseRows, pagination: { total: 2, totalPages: 1 } });
            }
            if (href.includes('/api/departments')) {
                return json({
                    data: [
                        { code: '10', name: 'المطبخ' },
                        { code: '20', name: 'الصالة' },
                    ],
                });
            }
            if (href.includes('/api/settings/main_settings')) {
                return json({ currency: 'SAR' });
            }
            return json({ error: 'NOT_FOUND', message: 'مسار غير معروف' }, 404);
        }),
    );
}

function renderRegister(config = REVENUES_CONFIG) {
    const client = new QueryClient({ defaultOptions: { queries: { retry: false } } });
    return render(
        <QueryClientProvider client={client}>
            <ToastProvider>
                <ConfirmProvider>
                    <FinanceRegister config={config} />
                </ConfirmProvider>
            </ToastProvider>
        </QueryClientProvider>,
    );
}

function dataRows(): HTMLElement[] {
    return screen.getAllByRole('row').slice(1) as HTMLElement[];
}

afterEach(() => {
    vi.unstubAllGlobals();
});

describe('سجل الإيرادات', () => {
    it('يعرض السجلات والمجموع من الالتقاط كما هي', async () => {
        stubFetch();
        renderRegister();

        await waitFor(() => {
            expect(screen.getByRole('table')).toBeTruthy();
        });

        expect(screen.getByRole('heading', { level: 1 }).textContent).toContain('الإيرادات');
        expect(dataRows()).toHaveLength(2);
        // 1000.50 + 250.25 = 1250.75 نصًّا على المليم.
        expect(screen.getByText(/1,250\.75/)).toBeTruthy();
        expect(screen.getByText('2 سجلًا')).toBeTruthy();

        const row = screen.getByText('مبيعات كاشير').closest('tr') as HTMLElement;
        expect(within(row).getByText('المطبخ')).toBeTruthy();
        expect(within(row).getByText('1,000.50', { exact: false })).toBeTruthy();
        expect(within(row).getByText('SAR')).toBeTruthy();
    });

    it('يترشّح بالقسم ويعود بـ«عرض الكل»', async () => {
        stubFetch();
        renderRegister();
        await waitFor(() => {
            expect(screen.getByRole('table')).toBeTruthy();
        });

        fireEvent.change(screen.getByLabelText('القسم'), { target: { value: '20' } });

        await waitFor(() => {
            expect(dataRows()).toHaveLength(1);
        });
        expect(screen.getByText('مبيعات صالة')).toBeTruthy();
        expect(screen.queryByText('مبيعات كاشير')).toBeNull();

        fireEvent.click(screen.getByRole('button', { name: 'عرض الكل' }));
        await waitFor(() => {
            expect(dataRows()).toHaveLength(2);
        });
    });

    it('يبحث في البيان والملاحظات ويكتب ملاحظة الاستيراد بالعربية', async () => {
        stubFetch();
        renderRegister();
        await waitFor(() => {
            expect(screen.getByRole('table')).toBeTruthy();
        });

        fireEvent.change(screen.getByLabelText('بحث'), { target: { value: 'قهوة' } });

        await waitFor(() => {
            expect(dataRows()).toHaveLength(1);
        });
        expect(screen.getByText(/مبيعات الكاشير/)).toBeTruthy();
        expect(screen.getByText(/فاتورة 88/)).toBeTruthy();
        expect(screen.getByText(/الأصناف: قهوة/)).toBeTruthy();
    });

    it('يعرض الفراغ والخطأ القابل لإعادة المحاولة', async () => {
        stubFetch({ revenue: { data: [] } });
        const first = renderRegister();
        await waitFor(() => {
            expect(screen.getByText('لا سجلات')).toBeTruthy();
        });
        first.unmount();

        vi.unstubAllGlobals();
        stubFetch({ status: 500 });
        renderRegister();
        await waitFor(() => {
            expect(screen.getByRole('alert')).toBeTruthy();
        });
        expect(screen.getByRole('button', { name: 'إعادة المحاولة' })).toBeTruthy();
    });
});

describe('سجل المصروفات', () => {
    it('يعرض نوع المصروف بتسميته العربية', async () => {
        stubFetch();
        renderRegister(EXPENSES_CONFIG);

        await waitFor(() => {
            expect(screen.getByRole('table')).toBeTruthy();
        });

        expect(screen.getByRole('heading', { level: 1 }).textContent).toContain('المصروفات');
        const countRow = screen.getByText('مشتريات').closest('tr') as HTMLElement;
        expect(within(countRow).getByText('فرق جرد')).toBeTruthy();

        const stockRow = screen.getByText('صرف للمخزن').closest('tr') as HTMLElement;
        expect(within(stockRow).getByText('صرف مخزون')).toBeTruthy();
    });
});
