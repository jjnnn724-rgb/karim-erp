type SortKey = 'date' | 'voucher' | 'description' | 'dept' | 'status' | 'amount';
type SortState = { key: SortKey; dir: 'asc' | 'desc' };
type PresetKey = PeriodPreset['key'];

const STATUS_TONE_CLASS: Record<StatusTone, string> = {
    success: 'text-success-text',
    warning: 'text-warning-text',
    danger: 'text-danger-text',
    neutral: 'text-muted',
};

const MONTH_PRESET: PeriodPreset =
    PRESETS.find((item) => item.key === 'month') ?? { key: 'month', label: 'هذا الشهر', from: '', to: '' };

function deltaHint(delta: number | string | null | undefined): string {
    if (delta === null || delta === undefined || delta === '') {
        return 'لا فترة مماثلة للمقارنة';
    }
    const value = Number(delta);
    if (!Number.isFinite(value)) {
        return 'لا فترة مماثلة للمقارنة';
    }
    if (value === 0) {
        return 'بلا تغيير عن الفترة السابقة';
    }
    // عزل LTR حول «250.0%» كي لا يسبق علامة النسبة الرقمَ في سياق عربي (bidi).
    return `${value > 0 ? 'ارتفاع' : 'انخفاض'} \u2066${Math.abs(value).toFixed(1)}%\u2069 عن الفترة السابقة`;
}

function StatusBadge({ row }: { row: CashRegisterRow }) {
    const status = row.request_status;
    if (status) {
        return (
            <span
                className={`inline-block whitespace-nowrap rounded-sm border border-hairline px-xs text-caption ${
                    STATUS_TONE_CLASS[dispatchStatusTone(status)]
                }`}
            >
                {dispatchStatusLabel(status)}
            </span>
        );
    }
    return (
        <span className="inline-block whitespace-nowrap rounded-sm border border-hairline px-xs text-caption text-muted">
            {row.autoGenerated ? 'آليّ بلا إذن' : 'يدوي'}
        </span>
    );
}

function SortHeader({
    label,
    sortKey,
    current,
    align,
    onSort,
}: {
    label: string;
    sortKey: SortKey;
    current: SortState;
    align: 'start' | 'end';
    onSort: (key: SortKey) => void;
}) {
    const active = current.key === sortKey;
    return (
        <th
            scope="col"
            aria-sort={active ? (current.dir === 'asc' ? 'ascending' : 'descending') : 'none'}
            className={`px-sm py-xs font-medium ${align === 'end' ? 'text-end' : 'text-start'}`}
        >
            <button type="button" onClick={() => onSort(sortKey)} className="inline-flex items-center gap-xxs">
                {label}
                <span aria-hidden="true" className="text-caption text-faint">
                    {active ? (current.dir === 'asc' ? '▲' : '▼') : '↕'}
                </span>
            </button>
        </th>
    );
}

