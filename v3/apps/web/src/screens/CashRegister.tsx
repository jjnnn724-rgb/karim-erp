interface VoucherStage {
    label: string;
    who: string;
    at: string;
    bad: boolean;
}

function buildStages(dispatch: VoucherDispatch): VoucherStage[] {
    const stages: VoucherStage[] = [];
    if (dispatch.createdBy) {
        stages.push({
            label: 'إعداد الطلب',
            who: String(dispatch.createdBy),
            at: String(dispatch.requestedAt ?? dispatch.date ?? ''),
            bad: false,
        });
    }
    if (dispatch.chefApprovedBy) {
        stages.push({
            label: 'اعتماد الشيف',
            who: String(dispatch.chefApprovedBy),
            at: String(dispatch.chefApprovedAt ?? ''),
            bad: false,
        });
    }
    if (dispatch.warehouseApprovedBy ?? dispatch.approvedBy) {
        stages.push({
            label: 'اعتماد المخزن',
            who: String(dispatch.warehouseApprovedBy ?? dispatch.approvedBy),
            at: String(dispatch.warehouseApprovedAt ?? dispatch.approvedDate ?? ''),
            bad: false,
        });
    }
    if (dispatch.chefRejectedBy) {
        stages.push({
            label: 'رفض الشيف',
            who: String(dispatch.chefRejectedBy),
            at: String(dispatch.chefRejectedAt ?? ''),
            bad: true,
        });
    }
    if (dispatch.warehouseRejectedBy ?? dispatch.rejectedBy) {
        stages.push({
            label: 'رفض المخزن',
            who: String(dispatch.warehouseRejectedBy ?? dispatch.rejectedBy),
            at: String(dispatch.warehouseRejectedAt ?? dispatch.rejectedDate ?? ''),
            bad: true,
        });
    }
    if (dispatch.kitchenReceivedBy) {
        stages.push({
            label: 'استلام المطبخ',
            who: String(dispatch.kitchenReceivedBy),
            at: String(dispatch.kitchenReceivedAt ?? ''),
            bad: false,
        });
    }
    return stages;
}

