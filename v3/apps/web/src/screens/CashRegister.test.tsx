function json(body: unknown, status = 200): Response {
    return new Response(JSON.stringify(body), {
        status,
        headers: { 'Content-Type': 'application/json' },
    });
}

const registerHtml = '<!DOCTYPE html><html><body><h1>كشف سجلّ الصرف</h1></body></html>';
const voucherHtml = '<!DOCTYPE html><html><body><h1>إذن صرف A4</h1></body></html>';

function html(body: string): Response {
    return new Response(body, {
        status: 200,
        headers: { 'Content-Type': 'text/html; charset=utf-8' },
    });
}

function stubFetch(options: { register?: unknown; voucher?: unknown; status?: number } = {}) {
    const mock = vi.fn(async (input: unknown) => {
        const href = String(input);
        if (options.status && options.status >= 400) {
            return json({ error: 'INTERNAL', message: 'تعذر تحميل السجل' }, options.status);
        }
        if (href.includes('/api/expense-register/voucher/') && href.includes('/html')) {
            return html(voucherHtml);
        }
        if (href.includes('/api/expense-register/html')) {
            return html(registerHtml);
        }
        if (href.includes('/api/expense-register/voucher/')) {
            return json(options.voucher ?? voucherBody);
        }
        if (href.includes('/api/expense-register')) {
            return json(options.register ?? registerBody);
        }
        return json({ error: 'NOT_FOUND', message: 'مسار غير معروف' }, 404);
    });
    vi.stubGlobal('fetch', mock);
    return mock;
}

interface PrintWindowStub {
    document: {
        open: () => void;
        close: () => void;
        write: (chunk: string) => void;
        title: string;
        querySelector: () => null;
    };
    focus: () => void;
    print: ReturnType<typeof vi.fn>;
    close: ReturnType<typeof vi.fn>;
}

function stubPrintWindow(): { win: PrintWindowStub; written: string[] } {
    const written: string[] = [];
    const win: PrintWindowStub = {
        document: {
            open: () => undefined,
            close: () => undefined,
            write: (chunk: string) => {
                written.push(chunk);
            },
            title: '',
            querySelector: () => null,
        },
        focus: () => undefined,
        print: vi.fn(),
        close: vi.fn(),
    };
    vi.spyOn(window, 'open').mockReturnValue(win as unknown as Window);
    return { win, written };
}

function renderScreen() {
    const client = new QueryClient({ defaultOptions: { queries: { retry: false } } });
    return render(
        <QueryClientProvider client={client}>
            <ToastProvider>
                <CashRegister />
            </ToastProvider>
        </QueryClientProvider>,
    );
}

function mainTable(): HTMLElement {
    const tables = screen.getAllByRole('table');
    return tables[tables.length - 1] as HTMLElement;
}

function bodyRows(): HTMLElement[] {
    return within(mainTable()).getAllByRole('row').slice(1);
}

function calledUrls(mock: ReturnType<typeof stubFetch>): string[] {
    return mock.mock.calls.map((call) => String(call[0]));
}

