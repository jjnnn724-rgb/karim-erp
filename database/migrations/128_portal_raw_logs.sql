-- (المسار portal) كانت تُعالج في المحرك مباشرة وتُكتب في attendance — لكنها
-- لا تُخزَّن أبدًا في attendance_logs (اللوج الخام)، فتختفي من أي شاشة/تدقيق/
-- إعادة تثبيت تقرأ البصمة الخام، وتُقرأ على أنها «الكاميرا خالي — بصمات مفقودة».
--
-- الحل: جهاز افتراضي ثابت كصاحب الـdeviceId الغائب في uq_attendance_logs_punch،
-- ثم مسار البوابة يُدرج كل بصمة ناجحة في attendance_logs (ON CONFLICT DO
-- NOTHING) بمصدر 'portal' — فتصبح البصمة الخام دليلًا موحّدًا للأجهزة والكاميرا.
--
-- ملاحظات الأمان:
--   • enabled = false: حلقة مزامنة ZK تتجاهله (لا اتصال TCP لجهاز افتراضي).
--   • الفريد (ipAddress, port) يمنع تكرار الصف عند إعادة التشغيل.
--   • لا تعديل على بيانات قائمة — إدراج مرجع واحد فقط.
-- ─────────────────────────────────────────────────────────────────────────────

INSERT INTO attendance_devices (name, "ipAddress", port, "commKey", enabled, "syncIntervalSeconds", status)
VALUES
    ('كاميرا التطبيق (بوابة السيرفر)', 'virtual-portal', 1, 0, false, 86400, 'disabled')
ON CONFLICT ("ipAddress", port) DO NOTHING;

COMMENT ON TABLE attendance_logs IS 'البصمة الخام الموحّدة: من أجهزة ZK (source=device) ومن كاميرا التطبيق عبر جهاز البوابة الافتراضي (source=portal) — دليل المحرك الوحيد';
