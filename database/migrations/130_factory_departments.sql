-- قرار المالك 2026-11-03: قسم الإنتاج (مثال: العصير G) يُسلّم إنتاجه لمنافذ
-- البيع الخارجية، ويُقيَّم التحويل تلقائيًا بسعر القائمة نفسه الذي تبيع به
-- المنفذ (بلا قائمة أسعار يدوية) — الإيراد يُقيَّد للمصنع (4000 دائن) ويُحمَّل
-- المنفذ (5000 مدين)، والتكلفة تبقى على المصنع. لا مساس بفواتير قديمة.
--
-- idempotent: IF NOT EXISTS — لا يفعل شيئًا عند إعادة التطبيق.
ALTER TABLE departments ADD COLUMN IF NOT EXISTS is_factory BOOLEAN NOT NULL DEFAULT FALSE;
COMMENT ON COLUMN departments.is_factory IS 'قسم إنتاج: تحويله لمنافذ البيع الخارجية يُقيَّم بسعر القائمة — إيراد للمصنع وتحميل على المنفذ';
