-- =====================================================
-- Migration 001: Schema Creation
-- NOTE: Uses IF NOT EXISTS to be safe for re-runs
-- =====================================================

-- Users
CREATE TABLE IF NOT EXISTS users (
    id BIGINT PRIMARY KEY,
    username VARCHAR(255) UNIQUE NOT NULL,
    password VARCHAR(255) NOT NULL,
    role VARCHAR(50) NOT NULL,
    name VARCHAR(255) NOT NULL,
    active BOOLEAN DEFAULT true
);

-- HR Departments
CREATE TABLE IF NOT EXISTS "hrDepartments" (
    id BIGINT PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    code VARCHAR(50) UNIQUE NOT NULL,
    manager VARCHAR(255)
);

-- Employees
CREATE TABLE IF NOT EXISTS employees (
    id BIGINT PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    "employeeId" VARCHAR(50) UNIQUE NOT NULL,
    department VARCHAR(50) REFERENCES "hrDepartments"(code) ON DELETE SET NULL,
    position VARCHAR(255),
    phone VARCHAR(50),
    email VARCHAR(255),
    "joinDate" VARCHAR(50),
    salary NUMERIC(10,2),
    status VARCHAR(50),
    "userId" BIGINT REFERENCES users(id) ON DELETE SET NULL,
    "iqamaExpiry" VARCHAR(50),
    "healthCertExpiry" VARCHAR(50),
    photo TEXT,
    "digitalFingerprint" VARCHAR(100),
    "cardId" VARCHAR(100)
);

-- Attendance
CREATE TABLE IF NOT EXISTS attendance (
    id BIGINT PRIMARY KEY,
    "employeeId" BIGINT REFERENCES employees(id) ON DELETE CASCADE,
    date VARCHAR(50) NOT NULL,
    "checkIn" VARCHAR(50),
    "checkOut" VARCHAR(50),
    late BOOLEAN DEFAULT false
);

-- Leave Types
CREATE TABLE IF NOT EXISTS "leaveTypes" (
    id BIGINT PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    days INT,
    icon VARCHAR(50),
    paid BOOLEAN
);

-- Leave Requests
CREATE TABLE IF NOT EXISTS "leaveRequests" (
    id BIGINT PRIMARY KEY,
    "employeeId" BIGINT REFERENCES employees(id) ON DELETE CASCADE,
    "leaveTypeId" BIGINT REFERENCES "leaveTypes"(id) ON DELETE SET NULL,
    "startDate" VARCHAR(50),
    "endDate" VARCHAR(50),
    status VARCHAR(50)
);

-- Payroll
CREATE TABLE IF NOT EXISTS payroll (
    id BIGINT PRIMARY KEY,
    "employeeId" BIGINT REFERENCES employees(id) ON DELETE CASCADE,
    month VARCHAR(50),
    year INT,
    "basicSalary" NUMERIC(10,2),
    allowances NUMERIC(10,2) DEFAULT 0,
    deductions NUMERIC(10,2) DEFAULT 0,
    "netSalary" NUMERIC(10,2),
    status VARCHAR(50)
);

-- Departments (Restaurant / Operations)
CREATE TABLE IF NOT EXISTS departments (
    id BIGINT PRIMARY KEY,
    code VARCHAR(50) UNIQUE NOT NULL,
    name VARCHAR(255) NOT NULL,
    icon VARCHAR(50),
    color VARCHAR(50)
);

-- Revenues
CREATE TABLE IF NOT EXISTS revenues (
    id BIGINT PRIMARY KEY,
    "deptId" VARCHAR(50) REFERENCES departments(code) ON DELETE CASCADE,
    source VARCHAR(255),
    amount NUMERIC(10,2),
    date VARCHAR(50),
    notes TEXT
);

-- Expenses
CREATE TABLE IF NOT EXISTS expenses (
    id BIGINT PRIMARY KEY,
    "deptId" VARCHAR(50) REFERENCES departments(code) ON DELETE CASCADE,
    "desc" VARCHAR(255),
    amount NUMERIC(10,2),
    date VARCHAR(50),
    notes TEXT,
    "autoGenerated" BOOLEAN DEFAULT false
);

-- Shelves
CREATE TABLE IF NOT EXISTS shelves (
    id BIGINT PRIMARY KEY,
    name VARCHAR(255),
    code VARCHAR(50),
    location VARCHAR(255),
    capacity NUMERIC(10,2),
    icon VARCHAR(50)
);

-- Inventory
CREATE TABLE IF NOT EXISTS inventory (
    id BIGINT PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    category VARCHAR(100),
    unit VARCHAR(50),
    qty NUMERIC(10,3),
    "avgCost" NUMERIC(10,2),
    "minQty" NUMERIC(10,3),
    "shelfId" BIGINT REFERENCES shelves(id) ON DELETE SET NULL,
    weight NUMERIC(10,3) DEFAULT 0
);

-- Inventory Transactions
CREATE TABLE IF NOT EXISTS "inventoryTx" (
    id BIGINT PRIMARY KEY,
    "itemId" BIGINT REFERENCES inventory(id) ON DELETE CASCADE,
    "itemName" VARCHAR(255),
    qty NUMERIC(10,3),
    type VARCHAR(50),
    date VARCHAR(50),
    cost NUMERIC(10,2),
    "totalValue" NUMERIC(10,2),
    notes TEXT,
    "invoiceNumber" VARCHAR(255),
    "supplierName" VARCHAR(255),
    weight NUMERIC(10,3),
    "dispatchId" VARCHAR(255)
);

-- Dispatches
CREATE TABLE IF NOT EXISTS dispatches (
    id BIGINT PRIMARY KEY,
    "deptCode" VARCHAR(50) REFERENCES departments(code) ON DELETE CASCADE,
    "deptName" VARCHAR(255),
    items JSONB,
    status VARCHAR(50),
    date VARCHAR(50),
    "createdBy" VARCHAR(100),
    notes TEXT
);

-- Recipes
CREATE TABLE IF NOT EXISTS recipes (
    id BIGINT PRIMARY KEY,
    name VARCHAR(255),
    "deptId" VARCHAR(50) REFERENCES departments(code) ON DELETE CASCADE,
    "sellingPrice" NUMERIC(10,2),
    "totalCost" NUMERIC(10,2),
    "costRatio" NUMERIC(10,2)
);

-- Purchase Invoices
CREATE TABLE IF NOT EXISTS "purchaseInvoices" (
    id BIGINT PRIMARY KEY,
    "invoiceNumber" VARCHAR(255),
    date VARCHAR(50),
    "supplierName" VARCHAR(255),
    "supplierPhone" VARCHAR(50),
    items JSONB,
    "totalAmount" NUMERIC(10,2),
    "paymentMethod" VARCHAR(50),
    notes TEXT,
    "createdAt" VARCHAR(50),
    "createdBy" VARCHAR(100)
);

-- Kitchen Returns
CREATE TABLE IF NOT EXISTS "kitchenReturns" (
    id BIGINT PRIMARY KEY,
    date VARCHAR(50),
    items JSONB,
    status VARCHAR(50),
    notes TEXT
);

-- Settings
CREATE TABLE IF NOT EXISTS settings (
    id VARCHAR(50) PRIMARY KEY,
    name VARCHAR(255),
    logo VARCHAR(100),
    "logoB64" TEXT,
    currency VARCHAR(50),
    "lowStockAlert" BOOLEAN,
    "workStartHour" INT
);

-- Weight Readings
CREATE TABLE IF NOT EXISTS "weightReadings" (
    id BIGINT PRIMARY KEY,
    weight NUMERIC(10,3),
    unit VARCHAR(50),
    date VARCHAR(50),
    "itemId" BIGINT REFERENCES inventory(id) ON DELETE CASCADE
);

-- Notifications
CREATE TABLE IF NOT EXISTS notifications (
    id BIGINT PRIMARY KEY,
    title VARCHAR(255),
    message TEXT,
    type VARCHAR(50),
    date VARCHAR(50),
    read BOOLEAN DEFAULT false
);

-- Full App State (For easy sync fallback)
CREATE TABLE IF NOT EXISTS app_state (
    id INT PRIMARY KEY DEFAULT 1,
    state_data JSONB,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
