-- ============================================================
-- Migration 085: إعادة تفعيل الوزن المتغير (Catch Weight) بنمط موسع
-- ============================================================
-- السياق: المايجريشن 060/084 فعّلا الوزن المتغير على الأصناف الموجودة آنذاك،
-- لكن الأصناف أعيد استيرادها لاحقًا عبر Excel (بلا أعمدة الوزن المتغير)
-- فعاد التفعيل صفرًا. هذه المايجريشن تعيد التفعيل بنمط أوسع يغطي أسماء
-- مثل "كتف غنم" و"فوركوارتر" و"مقادم بقر" التي لم تشملها الأنماط القديمة.
--
-- القاعدة (مطابقة backend/catch-weight-heuristic.js — حافظ على التزامن):
--   اسم يشبه اللحوم/الدواجن/الأسماك الطازجة  +  مخزون بالوزن (كجم/جرام)
--   ⇒ وزن متغير: طلب بالكرتون + صرف بالوزن الفعلي.
--   المخزون بالكرتون/الحبة يُترك كما هو (الطلب والصرف فيه متطابقان أصلًا).
--   الاستثناءات: بهارات/توابل/جريش/مرق... (إيجابيات كاذبة موثقة من القاعدة).
--
-- آمنة للتكرار (idempotent): لا تمس صنفًا مفعّلًا، ولا تغير الأرصدة.
-- ============================================================

UPDATE inventory
SET catch_weight_enabled = true,
    inventory_uom        = 'kg',
    packaging_uom        = COALESCE(NULLIF(packaging_uom, ''), 'كرتون'),
    catch_weight_uom     = 'kg',
    unit                 = 'kg'
WHERE catch_weight_enabled = false
  AND unit ~ '^(كيلو|كيلوجرام|كجم|كغ|kg|جرام|غرام|جم|g)$'
  AND (name ~ 'لحم|لحوم|عجل|بقر|بقري|غنم|خروف|خرفان|ضاني|كتف|ضلع|ضلوع|ريش|فخذ|افخاذ|أفخاذ|وتر|لوة|لوذ|ستيك|استيك|بتلو|سجق|بسطرمة|كفتة|كفته|كباب|كوارع|مقادم|كرشة|ممبار|شحم|كبدة|دجاج|فروج|صدور|جناح|جوانح|أجنحة|ورك|بروستر|فيليه|ناجت|نقانق|لانشون|مرتديلا|شاورما|برجر|سمك|روبي|جمبري|كاليماري|بلطي|دنيس|هامور|كنعد|ماكريل|سلطعون|كابوريا|استاكوزا|meat|beef|chicken|lamb|mutton|veal|fish|shrimp')
  AND name !~ 'بهارات|بهار|توابل|خلطات|تتبيلة|تتبيله|أعشاب|اعشاب|جريش|فريك|برغل|برجل|مرق|شوربة|مسحوق|حبوب';

-- سجل للمراجعة: الأصناف التي صارت عليها حالة الوزن المتغير (تظهر في لوج المايجريشن)
SELECT name AS "أصناف الوزن المتغير بعد التفعيل", unit, qty
FROM inventory
WHERE catch_weight_enabled = true
ORDER BY name;
