-- «الشحم والكبدة بالكيلو مش كرتون» — هذان الصنفان يُطلبان ويُخزنان بالوزن
-- مباشرة (منتجات مفتوحة بلا تعبئة كراتين)، فتفعيل الوزن المتغير عليهما كان
-- يفرض على الأقسام الطلب بعدد الكراتين خطأً.
-- المايجريشن 085 فعّلهما مع بقية اللحوم؛ هذا التصحيح يعيدهما للتدفق العادي
-- (طلب بالكيلو ← اعتماد بالكيلو) ويطابق كشف backend/catch-weight-heuristic.js
-- الذي أُضيفت إليه «شحم|كبدة» قائمة الاستبعاد بنفس القرار.
-- آمنة للتكرار (idempotent).
-- ============================================================

UPDATE inventory
SET catch_weight_enabled = false,
    packaging_uom        = NULL,
    unit                 = 'كيلو'
WHERE name IN ('شحم بطن', 'كبدة باليكلو');

-- سجل مراجعة: ما تبقى مفعّلًا من الوزن المتغير بعد التصحيح
SELECT name AS "أصناف الوزن المتغير بعد التصحيح", unit, qty
FROM inventory
WHERE catch_weight_enabled = true
ORDER BY name;
