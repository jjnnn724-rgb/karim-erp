-- Configurable reminder dates and idempotent audit of scheduled notifications.
-- ZATCA due dates are intentionally entered from a verified official notice;
-- this migration does not infer statutory deadlines.
BEGIN;

CREATE TABLE IF NOT EXISTS compliance_deadlines (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(255) NOT NULL,
    due_date DATE NOT NULL,
    reference_url TEXT,
    active BOOLEAN NOT NULL DEFAULT true,
    created_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT compliance_deadline_title_nonempty CHECK (length(trim(title)) > 0)
);

CREATE INDEX IF NOT EXISTS compliance_deadlines_active_due_idx
    ON compliance_deadlines (due_date, id) WHERE active = true;

CREATE TABLE IF NOT EXISTS compliance_alert_events (
    event_key VARCHAR(255) PRIMARY KEY,
    notification_count INTEGER NOT NULL CHECK (notification_count > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

COMMIT;
