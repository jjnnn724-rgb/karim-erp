const pool = new Pool({
    host: env.DB_HOST, port: Number(env.DB_PORT) || 5432,
    user: env.DB_USER, password: env.DB_PASSWORD, database: env.DB_NAME,
});

(async () => {
    // sanity: كل طبق موجود واسمه يطابق
    const ids = DISHES.map((d) => d[0]);
    const { rows: existing } = await pool.query('SELECT id, name FROM buffet_dishes WHERE id = ANY($1) ORDER BY id', [ids]);
    const byId = new Map(existing.map((r) => [Number(r.id), r.name]));
    let bad = 0;
    for (const [id, name] of DISHES) {
        if (byId.get(id) !== name) {console.log('MISMATCH #' + id, 'expected:', name, '| got:', byId.get(id)); bad++;}
    }
    if (bad) {console.error('أسماء غير مطابقة — توقف'); process.exit(1);}
    if (DRY) {
        const total = DISHES.reduce((s, d) => s + d[2].length, 0);
        console.log(`dry-run: ${DISHES.length} أطباق · ${total} مكوّن — لم يُكتب شيء`);
        await pool.end();
        return;
    }
    const client = await pool.connect();
    try {
        await client.query('BEGIN');
        let lines = 0;
        for (const [id, , ingredients] of DISHES) {
            await client.query('DELETE FROM buffet_ingredients WHERE dish_id = $1', [id]);
            for (let i = 0; i < ingredients.length; i++) {
                const [name, qty, unit] = ingredients[i];
                await client.query(
                    'INSERT INTO buffet_ingredients (dish_id, position, name, qty, unit) VALUES ($1, $2, $3, $4, $5)',
                    [id, i + 1, name, qty, unit],
                );
                lines++;
            }
        }
        await client.query('COMMIT');
        console.log(`committed: ${DISHES.length} أطباق · ${lines} مكوّنًا`);
    } catch (e) {
        await client.query('ROLLBACK');
        console.error('ROLLBACK:', e.message);
        process.exit(1);
    } finally {
        client.release();
        await pool.end();
    }
})().catch((e) => { console.error('ERR:', e.message); process.exit(1); });
