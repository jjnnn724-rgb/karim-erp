#!/usr/bin/env node
'use strict';
/**
 * backfill-transfer-expenses.js — قيود مصروفات التحويلات المنفَّذة سابقًا
 * ═══════════════════════════════════════════════════════════════════════════
 * نظام التحويلات (dept-transfer-routes.js) صار يكتب قيدَي مصروف متقابلين
 * لكل تحويل منفَّذ داخل نفس المعاملة:
 *   صادر سالب على القسم المرسل · وارد موجب على القسم المستلم
 * (adjustmentType = 'inventory_transfer') — وهما مصدر شاشة تحليل التكاليف.
 * التحويلات التي نُفِّذت قبل إضافة هذا السلوك بلا قيود، فيُكملها هذا السكربت.
 *
 * الأمان:
 *   • معاينة افتراضيًا — لا كتابة إلا مع --apply.
 *   • idempotent: معرّف المصروف مشتق من (معرّف التحويل، الاتجاه) عبر sha256
 *     بنفس دالة expenseIdFor في الخادم، والإدراج ON CONFLICT (id) DO NOTHING.
 *   • لا يمس إلا التحويلات status='received' بقيمة أكبر من صفر.
 *
 * الاستخدام:
 *   node scripts/backfill-transfer-expenses.js            # معاينة
 *   node scripts/backfill-transfer-expenses.js --apply    # كتابة
 */

const crypto = require('crypto');
const { pool } = require('../backend/shared-pool');

const APPLY = process.argv.includes('--apply');
const money = (v) => Number(v || 0).toLocaleString('en-US', { minimumFractionDigits: 2, maximumFractionDigits: 2 });
const log = (...args) => console.log('[TRANSFER-EXP]', ...args);

/** مطابق لـ expenseIdFor في backend/dept-transfer-routes.js. */
function expenseIdFor(transferId, side) {
    const h = crypto.createHash('sha256').update('transfer-expense:' + transferId + ':' + side).digest();
    return Number(BigInt('0x' + h.subarray(0, 6).toString('hex')));
}

function riyadhDay(value) {
    return new Intl.DateTimeFormat('en-CA', { timeZone: 'Asia/Riyadh' }).format(new Date(value));
}

async function main() {
    log(`الوضع: ${APPLY ? 'كتابة' : 'معاينة فقط — أضف --apply'}`);
    const { rows } = await pool.query(
        `SELECT t.id, t.transfer_number, t.created_at, t.metadata,
                COUNT(it.id)::int AS lines,
                COALESCE(SUM(COALESCE(NULLIF(it.received_qty, 0), it.requested_qty) * COALESCE(it.unit_cost, 0)), 0) AS value
           FROM inventory_transfers t
           JOIN inventory_transfer_items it ON it.transfer_id = t.id
          WHERE t.status = 'received'
          GROUP BY t.id
          ORDER BY t.created_at`);
    let created = 0;
    let skipped = 0;
    let pending = 0;
    for (const t of rows) {
        const value = Number(Number(t.value).toFixed(4));
        const src = t.metadata && t.metadata.sourceDeptCode ? String(t.metadata.sourceDeptCode) : '';
        const dst = t.metadata && t.metadata.destDeptCode ? String(t.metadata.destDeptCode) : '';
        if (!(value > 0) || !src || !dst) {
            log(`  تخطٍّ ${t.transfer_number}: قيمة=${money(value)} مصدر=${src || '؟'} وجهة=${dst || '؟'}`);
            skipped++;
            continue;
        }
        const day = riyadhDay(t.created_at);
        const base = 'تحويل مخزون ' + t.transfer_number;
        const entries = [
            [expenseIdFor(t.id, 'out'), src, base + ' — صادر إلى ' + dst, -value, day, 'transfer:' + t.id + ':out'],
            [expenseIdFor(t.id, 'in'), dst, base + ' — وارد من ' + src, value, day, 'transfer:' + t.id + ':in'],
        ];
        const existing = await pool.query(
            'SELECT id FROM expenses WHERE id = ANY($1::bigint[])',
            [entries.map((e) => e[0])]);
        if (existing.rowCount === entries.length) {
            skipped++;
            continue;
        }
        log(`  ${t.transfer_number}: ${src} → ${dst} قيمة=${money(value)} يوم=${day} (${existing.rowCount}/2 موجود)`);
        if (!APPLY) { pending++; continue; }
        const client = await pool.connect();
        try {
            await client.query('BEGIN');
            for (const e of entries) {
                const res = await client.query(
                    `INSERT INTO expenses (id, "deptId", "desc", amount, date, notes, "autoGenerated", category, "adjustmentType")
                     VALUES ($1,$2,$3,$4,$5,$6,true,'تحويلات','inventory_transfer')
                     ON CONFLICT (id) DO NOTHING`, e);
                created += res.rowCount || 0;
            }
            await client.query('COMMIT');
        } catch (error) {
            await client.query('ROLLBACK').catch(() => {});
            throw error;
        } finally {
            client.release();
        }
    }
    log(`النتيجة: أُنشئ ${created} · موجود/متخطّى ${skipped} · بانتظار --apply ${pending}`);
}

main()
    .catch((e) => { console.error('[TRANSFER-EXP] FAILED:', e.message); process.exitCode = 1; })
    .finally(() => pool.end());
