const fs = require('fs');
const path = require('path');
const vm = require('vm');

const APP = path.join(__dirname, '..', 'frontend', 'app');
const V2 = path.join(APP, 'js', 'v2');
const REPO = path.join(V2, 'data', 'dept-detail.js');
const SCREEN = path.join(V2, 'screens', 'departments.js');
const V2_HTML = path.join(APP, 'v2.html');
const REV = (fs.readFileSync(V2_HTML, 'utf8').match(/js\/v2\/preview\.js\?v=([0-9.]+)/) || [])[1];

const read = (p) => fs.readFileSync(p, 'utf8');

function loadEsm(file, injections = {}, collect = []) {
    const stripped = read(file)
        .split('\n')
        .filter((line) => !/^\s*import\b|^\s*from\s*'[^']*';?\s*$/.test(line))
        .join('\n')
        .replace(/^export\s+/gm, '');
    const src = collect.length
        ? `${stripped}\n;Object.assign(globalThis, {${collect.join(', ')}});`
        : stripped;
    const context = {
        console, JSON, String, Number, Boolean, Array, Object, RegExp, Error,
        Date, Math, Promise, Set, Map, Intl, encodeURIComponent,
        ...injections,
    };
    vm.createContext(context);
    vm.runInContext(src, context, { filename: file });
    return context;
}

function repoStub(impl) {
    const calls = [];
    const apiFetch = jest.fn(async (p, opts) => {
        calls.push({ path: p, method: (opts && opts.method) || 'GET', body: opts && opts.body });
        return impl ? impl(p, opts) : {};
    });
    return { apiFetch, calls };
}

describe('تفاصيل القسم — الحسابات', () => {
    test('خريطة الكاشيرات وإيرادها ولون الهوية بنفس القواعد', () => {
        const ctx = loadEsm(REPO, {}, ['CASHIER_DEPT_MAP', 'cashierRevenueIn', 'deptIdentityColor', 'mappedCashierNos']);
        expect(ctx.CASHIER_DEPT_MAP).toEqual({ 1: 'CAF', 4: 'external_sales', 5: 'external_sales', 6: 'G', 9: 'open_buffet' });
        const revs = [
            { deptId: 'ys_cc_9', amount: 100, date: '2026-10-10' },
            { deptId: 'ys_cc_2', amount: 999, date: '2026-10-10' },
            { deptId: 'ys_cc_9', amount: 50, date: '2026-09-01' },
        ];
        expect(ctx.cashierRevenueIn(revs, ['9'], '2026-10-01', '2026-10-15')).toBe(100);
        expect(ctx.cashierRevenueIn(revs, ['9'], null, null)).toBe(150);
        expect(ctx.deptIdentityColor({ color: '#AABBCC' })).toBe('#AABBCC');
        expect(ctx.deptIdentityColor({})).toBe('#D4A843');
    });

    test('أبواب الإيراد/المصروف بنفس المسارات والحمولات', async () => {
        const { apiFetch, calls } = repoStub(() => ({}));
        const ctx = loadEsm(REPO, { apiFetch }, ['createRevenue', 'createExpense']);
        await ctx.createRevenue({ deptId: 'CAF', amount: 100, date: '2026-10-15', source: 'بيع', notes: '' });
        await ctx.createExpense({ deptId: 'CAF', amount: 50, date: '2026-10-15', desc: 'شراء', category: 'تشغيل', notes: '' });
        expect(calls.map((c) => `${c.method} ${c.path}`)).toEqual(['POST /revenues', 'POST /expenses']);
        expect(JSON.parse(calls[0].body)).toEqual({ deptId: 'CAF', amount: 100, date: '2026-10-15', source: 'بيع', notes: '' });
        expect(JSON.parse(calls[1].body).autoGenerated).toBe(false);
        await expect(ctx.createRevenue({ deptId: '', amount: 0, date: '', source: '' })).rejects.toThrow('بيانات غير صحيحة');
    });
});

describe('تفاصيل القسم — عقد الشاشة', () => {
    const src = () => read(SCREEN);

    test('السجل + التفاصيل + الإيراد/المصروف حاضرة', () => {
        const s = src();
        for (const k of ['data-v2-detail', 'data-v2-dfrom', 'data-v2-dto', 'data-v2-dall',
            'data-v2-rev-add', 'data-v2-exp-add', 'data-v2-m-go', 'computeDeptDetail',
            'نسبة التكلفة', 'أذون الصرف للقسم']) {
            expect(s).toContain(k);
        }
    });

    test('بلا شبكة مباشرة ولا معالج سطري', () => {
        const s = src().replace(/\/\*[\s\S]*?\*\//g, '');
        expect(s).not.toMatch(/\bapiFetch\b/);
        expect(s).not.toMatch(/[^a-zA-Z]fetch\(/);
        expect(s).toMatch(/from '\.\.\/data\/dept-detail\.js\?v=/);
        expect(s.match(/\son[a-z]+\s*=\s*["']/g) || []).toHaveLength(0);
    });

    test('الوحدة الموحدة', () => {
        expect(REV).toBeTruthy();
        for (const f of [REPO, SCREEN]) {
            const versions = [...read(f).matchAll(/\?v=([0-9.]+)/g)].map((m) => m[1]);
            expect(versions.length).toBeGreaterThan(0);
            for (const v of versions) {expect(v).toBe(REV);}
        }
    });
});
