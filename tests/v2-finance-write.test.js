        await ctx.deleteExpense(9);
        expect(calls.map((c) => `${c.method} ${c.p}`)).toEqual([
            'PUT /revenues/5', 'DELETE /revenues/5', 'PUT /expenses/9', 'DELETE /expenses/9',
        ]);
        // الحمولات مُهيّأة (ترقيم + تقليم) والحذف بلا جسم — لا خداع بصري.
