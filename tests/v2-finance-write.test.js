/** إزالة التعليقات — الادعاء المكتوب فيها ليس عقدًا سلوكيًا. */
const stripComments = (s) => s.replace(/\/\*[\s\S]*?\*\//g, '').replace(/(^|[^:])\/\/[^\n]*/g, '$1');

function loadEsm(file, injections = {}, wanted = null) {
    let src = read(file).replace(/^\s*import\s+[^\n]*$/gm, '').replace(/^\s*export\s+(const|let)\s+/gm, 'var ');
    src = src.replace(/^\s*export\s+/gm, '');
    const ctx = { console, ...injections };
    vm.createContext(ctx);
    new vm.Script(src, { filename: file }).runInContext(ctx);
    const out = {};
    if (wanted) {for (const k of wanted) {out[k] = ctx[k];}}
    else {for (const k of Object.keys(ctx)) {if (k !== 'console') {out[k] = ctx[k];}}}
    return out;
}

