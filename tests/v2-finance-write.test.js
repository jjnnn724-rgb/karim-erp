/** OPEN_ENTITY_WRITE_ROLES — صفتا revenues و expenses. */
function serverRoles(entity) {
    const at = SCHEMA_SRC.indexOf('OPEN_ENTITY_WRITE_ROLES');
    if (at < 0) {throw new Error('لا يوجد OPEN_ENTITY_WRITE_ROLES');}
    const win = SCHEMA_SRC.slice(at, at + 4000);
    const m = win.match(new RegExp(`['"]?${entity}['"]?:\\s*\\[([^\\]]*)\\]`));
    if (!m) {throw new Error(`لا صف ${entity} داخل OPEN_ENTITY_WRITE_ROLES`);}
    return m[1].split(',').map((s) => s.trim().replace(/['"]/g, '')).filter(Boolean);
}

/** whitelist حقول الكتابة للكيان. */
function serverWriteable(entity) {
    const m = SCHEMA_SRC.match(new RegExp(`${entity}:\\s*\\{[\\s\\S]*?writeable:\\s*\\[([^\\]]*)\\]`));
    if (!m) {throw new Error(`لا writeable لـ ${entity}`);}
    return m[1].split(',').map((s) => s.trim().replace(/['"]/g, '')).filter(Boolean);
}

/** maxLength للكيان — أرقام الحدود التي يستشهد بها الخادم في رفضه. */
function serverMaxLength(entity) {
    const m = SCHEMA_SRC.match(new RegExp(`${entity}:\\s*\\{[\\s\\S]*?maxLength:\\s*\\{([^}]*)\\}`));
    if (!m) {throw new Error(`لا maxLength لـ ${entity}`);}
    const out = {};
    for (const pair of m[1].split(',')) {
        const [k, v] = pair.split(':');
        if (k && v) {out[k.trim()] = Number(v.trim());}
    }
    return out;
}

/** مفاتيح جسم persistUpdate في legacy finance.js — القديم هو المرجع لا الذاكرة. */
function legacyKeys(entity) {
    const m = LEGACY_SRC.match(new RegExp(`persistUpdate\\('${entity}',\\s*id,\\s*\\{([^}]*)\\}`));
    if (!m) {throw new Error(`لا persistUpdate لـ ${entity} في finance.js`);}
    return m[1].split(',').map((s) => s.trim()).filter(Boolean);
}

