// ────────────────────────────────────────────────────────────────────────────
// dept-cost.test.js — كلفة الأقسام: كل صرف/فرق جرد يُسجَّل مصروفًا على القسم
// يغطي: مولّد مصروف فروق الجرد النقي + اعتماد النطاقات/التطبيع في الاستوديو
// ────────────────────────────────────────────────────────────────────────────
const {
    buildStocktakeExpense,
} = require('../backend/inventory-control-routes');
const stocktaking = require('../backend/stocktaking-routes');
const { normalizeScopeFilter, computeVariance } = stocktaking;

describe('buildStocktakeExpense — عجز الجرد يتحول مصروفًا موجبًا على القسم', () => {
    const base = { itemName: 'دجاج مجمد', unit: 'كجم', auditNumber: 'AUD-2026-0001', txId: 12345, countedAt: '2026-08-30T10:00:00.000Z' };

    test('نقص 2 كجم بقيمة 70 → مصروف +70 على قسم المطبخ', () => {
        const row = buildStocktakeExpense({ ...base, varianceQty: -2, varianceValue: -70, deptCode: 'kitchen' });
        expect(row.amount).toBe(70);
        expect(row.deptId).toBe('kitchen');
        expect(row.adjustmentType).toBe('count_correction');
        expect(row.category).toBe('مواد خام');
        expect(row.autoGenerated).toBe(true);
        expect(row.desc).toContain('عجز جرد');
        expect(row.desc).toContain('دجاج مجمد');
        expect(row.desc).toContain('2 كجم');
        expect(row.date).toBe('2026-08-30');
        expect(row.notes).toContain('AUD-2026-0001');
        expect(row.notes).toContain('12345');
    });

    test('زيادة 1 وحدة بقيمة 12.5 → مصروف سالب (دائن) يعكس الكلفة', () => {
        const row = buildStocktakeExpense({ ...base, itemName: 'أرز', unit: 'كجم', varianceQty: 1, varianceValue: 12.5, deptCode: 'kitchen' });
        expect(row.amount).toBe(-12.5);
        expect(row.desc).toContain('زيادة جرد');
        expect(row.desc).not.toContain('عجز');
    });

    test('مخزن بلا قسم مرتبط → مصروف بلا قسم (deptId null) ولا ينهار', () => {
        const row = buildStocktakeExpense({ ...base, varianceQty: -3, varianceValue: -90, deptCode: null });
        expect(row.deptId).toBeNull();
        expect(row.amount).toBe(90);
    });

    test('وحدة مفقودة تُعوّض بـ"وحدة" وقيم الكسور تُقرَّب لعشورتين', () => {
        const row = buildStocktakeExpense({ ...base, itemName: 'زيت', unit: '', varianceQty: -0.333333, varianceValue: -10.0055, deptCode: 'kitchen' });
        expect(row.desc).toContain('(0.333 وحدة)');
        expect(row.amount).toBe(10.01);
    });

    test('عدم السماح بتحميل عجز على قسم غير موجود ككود — يمر كما هو (المسؤولية على FK)', () => {
        // deptCode يمر كما هو؛ أي كود غير صحيح سيرفضه قيد المفتاح الأجنبي في القاعدة
        const row = buildStocktakeExpense({ ...base, varianceQty: -1, varianceValue: -10, deptCode: 'open_buffet' });
        expect(row.deptId).toBe('open_buffet');
    });
});

describe('computeVariance — أساس الفروق الذي يغذي المصروف', () => {
    test('نقص/زيادة/تطابق بقيم مدورة', () => {
        expect(computeVariance(8, 10, 35)).toEqual({ varianceQty: -2, varianceValue: -70 });
        expect(computeVariance(11, 10, 35)).toEqual({ varianceQty: 1, varianceValue: 35 });
        expect(computeVariance(10, 10, 35)).toEqual({ varianceQty: 0, varianceValue: 0 });
    });
});

describe('normalizeScopeFilter — نطاق جلسة الجرد آمن كما في الاستوديو', () => {
    test('يحافظ على الأنماط المعروفة ويسقط الحقول الغريبة', () => {
        expect(normalizeScopeFilter({ mode: 'category', category: 'مواد', search: '', hack: 'x' }))
            .toEqual({ mode: 'category', category: 'مواد', search: null });
        expect(normalizeScopeFilter({ mode: 'weird' })).toEqual({ mode: 'all', category: null, search: null });
    });
});

describe('تكامل الاستوديو — واجهة stocktaking-routes تظل متاحة', () => {
    test('الدوال النقية الأصلية لم تتأثر بتغييرات كلفة الأقسام', () => {
        expect(typeof stocktaking.computeVariance).toBe('function');
        expect(typeof stocktaking.validateCountPayload).toBe('function');
        const v = stocktaking.validateCountPayload({ countedQty: 5, notes: 'عدّ يدوي' });
        expect(v.errors).toEqual([]);
        expect(v.countedQty).toBe(5);
    });
});
