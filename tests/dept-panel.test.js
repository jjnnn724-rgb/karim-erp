// لوحة رئيس القسم: بوابات الوصول (هوية + دور)، نطاق القسم، تصنيف مصادر
// المصروفات، تجميع المبالغ (المبالغ غير الرقمية تُتخطى لا تُحسب صفرًا)،
// وفحص حي للمسار على قاعدة بيانات حقيقية مع تنظيف ذاتي.
