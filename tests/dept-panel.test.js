const {
    canAccessDeptPanel,
    resolvePanelDept,
    classifyExpenseSource,
    aggregatePanelExpenses,
    DEPT_PANEL_ROLES,
    EXPENSE_SOURCE_LABELS,
} = require('../backend/warehouse-routes');
const path = require('path');
require('dotenv').config({ path: path.join(__dirname, '..', '.env') });
const { signAccessToken } = require('../backend/cashier-module/jwt-middleware');

describe('canAccessDeptPanel — بوابة الهوية والدور معًا', () => {
    test('بلا هوية (null/undefined/بدون id) تُرفض 401 حتى لو الدور مسموح', () => {
        expect(canAccessDeptPanel(null)).toEqual({ ok: false, code: 'IDENTITY_REQUIRED' });
        expect(canAccessDeptPanel(undefined)).toEqual({ ok: false, code: 'IDENTITY_REQUIRED' });
        expect(canAccessDeptPanel({ role: 'admin' })).toEqual({ ok: false, code: 'IDENTITY_REQUIRED' });
        expect(canAccessDeptPanel({ id: null, role: 'admin' })).toEqual({ ok: false, code: 'IDENTITY_REQUIRED' });
    });

    test('رئيس قسم بلا dept_code مرفوض — لا فرض قسم افتراضي', () => {
        expect(canAccessDeptPanel({ id: 5, role: 'dept_head' })).toEqual({ ok: false, code: 'DEPT_HEAD_WITHOUT_DEPARTMENT' });
        expect(canAccessDeptPanel({ id: 5, role: 'dept_head', dept_code: '   ' })).toEqual({ ok: false, code: 'DEPT_HEAD_WITHOUT_DEPARTMENT' });
    });

    test('الأدوار المسموحة الخمسة تمر (dept_head بقسمه + kitchen + admin + manager + accountant)', () => {
        expect(canAccessDeptPanel({ id: 1, role: 'admin' })).toEqual({ ok: true });
        expect(canAccessDeptPanel({ id: 2, role: 'manager' })).toEqual({ ok: true });
        expect(canAccessDeptPanel({ id: 3, role: 'kitchen' })).toEqual({ ok: true });
        expect(canAccessDeptPanel({ id: 4, role: 'dept_head', dept_code: 'salads' })).toEqual({ ok: true });
        // المحاسب أُضيف للقراءة — تكاليف الأقسام من صميم عمله (مُوثَّق في warehouse-routes)
    });

    test('الأدوار خارج الخريطة تُرفض 403 (warehouse/employee/hr)', () => {
        expect(canAccessDeptPanel({ id: 6, role: 'warehouse' })).toEqual({ ok: false, code: 'ROLE_NOT_ALLOWED' });
        expect(canAccessDeptPanel({ id: 7, role: 'employee' })).toEqual({ ok: false, code: 'ROLE_NOT_ALLOWED' });
        expect(canAccessDeptPanel({ id: 8, role: 'hr' })).toEqual({ ok: false, code: 'ROLE_NOT_ALLOWED' });
        expect(canAccessDeptPanel({ id: 9, role: 'accountant' })).toEqual({ ok: true });
    });

    test('خريطة الأدوار موقوفة عن التغيير ومتوافقة مع الواجهة', () => {
        expect(DEPT_PANEL_ROLES).toEqual(['admin', 'manager', 'dept_head', 'kitchen', 'sous_chef', 'accountant']);
    });
});

describe('resolvePanelDept — نطاق اللوحة وقفل رئيس القسم في قسمه', () => {
    test('dept_head يُجبر على قسمه حتى لو طلب قسمًا آخر (DEPT_MISMATCH)', () => {
        expect(resolvePanelDept({ role: 'dept_head', dept_code: 'salads' }, 'fnb')).toEqual({ ok: false, code: 'DEPT_MISMATCH' });
        expect(resolvePanelDept({ role: 'dept_head', dept_code: 'salads' }, 'SALADS')).toEqual({ ok: true, deptCode: 'salads' });
        // تحديث 2026-10-02: الإرجاع بالكود الأصلي كما في القاعدة (ترقية 2026-10-01) —
        // بحث القسم في SQL حساس لحالة الأحرف (SERVICE ≠ service)، المقارنة بلا حساسية فقط.
        expect(resolvePanelDept({ role: 'dept_head', dept_code: 'Salads' }, null)).toEqual({ ok: true, deptCode: 'Salads' });
    });

    test('dept_head بلا قسم مرفوض ولا يقع في النظرة العامة', () => {
        expect(resolvePanelDept({ role: 'dept_head', dept_code: null }, null)).toEqual({ ok: false, code: 'DEPT_HEAD_WITHOUT_DEPARTMENT' });
    });

    test('kitchen (الشيف العمومي) يرى المطبخ افتراضيًا ويمكنه التركيز على قسم فرعي', () => {
        expect(resolvePanelDept({ role: 'kitchen' }, null)).toEqual({ ok: true, deptCode: 'kitchen' });
        expect(resolvePanelDept({ role: 'kitchen' }, 'butcher')).toEqual({ ok: true, deptCode: 'butcher' });
    });

    test('admin/manager: أي قسم يطلبونه، وبلا طلب = نظرة عامة (null)', () => {
        expect(resolvePanelDept({ role: 'admin' }, 'sweets')).toEqual({ ok: true, deptCode: 'sweets' });
        expect(resolvePanelDept({ role: 'manager' }, null)).toEqual({ ok: true, deptCode: null });
    });
});

describe('classifyExpenseSource — تصنيف المصدر من مفردات النظام الفعلية', () => {
    test('dispatch / dispatch_return / count_correction تُصنف بأعمدة النظام', () => {
        expect(classifyExpenseSource({ adjustmentType: 'dispatch', autoGenerated: true })).toBe('dispatch');
        expect(classifyExpenseSource({ adjustmentType: 'DISPATCH_RETURN', autoGenerated: true })).toBe('dispatch_return');
        expect(classifyExpenseSource({ adjustmentType: 'count_correction', autoGenerated: true })).toBe('stocktaking');
    });

    test('يدوي: بلا نوع وبلا توليد آلي = manual حتى لو الحقول فارغة', () => {
        expect(classifyExpenseSource({})).toBe('manual');
        expect(classifyExpenseSource({ adjustmentType: null, autoGenerated: false })).toBe('manual');
        expect(classifyExpenseSource(null)).toBe('manual');
    });

    test('أنواع تلقائية أخرى غير معروفة = auto_other لا manual (لا إخفاء أصل المصروف)', () => {
        expect(classifyExpenseSource({ adjustmentType: 'payroll', autoGenerated: true })).toBe('auto_other');
        expect(classifyExpenseSource({ adjustmentType: 'transfer', autoGenerated: false })).toBe('auto_other');
    });

    test('تسميات المصادر عربية ومكتملة للواجهة', () => {
        expect(EXPENSE_SOURCE_LABELS).toEqual({
            dispatch: 'صرف مخزني',
            dispatch_return: 'عكس صرف (مرتجع)',
            purchase_direct: 'مشتريات مباشرة للقسم',
            stocktaking: 'فروق جرد',
            auto_other: 'تلقائي آخر',
            manual: 'يدوي',
        });
    });
});

describe('aggregatePanelExpenses — التجميع والقفز على المبالغ الفاسدة', () => {
    test('يجمع الإجمالي والعدد والتصنيف والشهور بدقة التقريب الثلاثية', () => {
        const rows = [
            { amount: 10, adjustmentType: 'dispatch', autoGenerated: true, date: '2026-01-05' },
            { amount: 2.333333, adjustmentType: null, autoGenerated: false, date: '2026-01-20' },
            { amount: -5, adjustmentType: 'dispatch_return', autoGenerated: true, date: '2026-02-01' },
        ];
        const result = aggregatePanelExpenses(rows);
        expect(result.total).toBe(7.333);
        expect(result.count).toBe(3);
        expect(result.skippedInvalid).toBe(0);
        expect(result.bySource.dispatch).toEqual({ count: 1, total: 10 });
        expect(result.bySource.dispatch_return).toEqual({ count: 1, total: -5 });
        expect(result.bySource.manual).toEqual({ count: 1, total: 2.333 });
        expect(result.monthly['2026-01']).toBe(12.333);
        expect(result.monthly['2026-02']).toBe(-5);
    });

    test('المبالغ غير الرقمية تُتخطى بعدّها skippedInvalid ولا تُحسب صفرًا (إصلاح ثغرة التجميع)', () => {
        const result = aggregatePanelExpenses([
            { amount: 'abc', date: '2026-01-01' },
            { amount: null, date: '2026-01-02' },
            { amount: undefined, date: '2026-01-03' },
            { amount: NaN, date: '2026-01-04' },
            { amount: 7, date: '2026-01-05' },
        ]);
        expect(result.skippedInvalid).toBe(4);
        expect(result.count).toBe(1);
        expect(result.total).toBe(7);
    });

    test('مدخلات شاذة: قائمة فارغة / غير مصفوفة → تجميع صامت بلا انفجار', () => {
        expect(aggregatePanelExpenses([])).toEqual({ total: 0, count: 0, skippedInvalid: 0, bySource: {}, monthly: {}, labels: EXPENSE_SOURCE_LABELS });
        expect(aggregatePanelExpenses(null).count).toBe(0);
        expect(aggregatePanelExpenses('not-a-list').total).toBe(0);
    });
});

describe('GET /api/warehouse/dept-panel — المسار الحي على قاعدة حقيقية', () => {
    const { pool } = require('../backend/shared-pool');
    let server;
    let baseUrl;
    let adminToken;
    let headSaladsToken;
    let keeperToken;
    const createdExpenseIds = [];

    beforeAll(async () => {
        process.env.NODE_ENV = process.env.NODE_ENV || 'development';
        const app = require('express')();
        app.use(require('express').json());
        app.use('/api/warehouse', (req, _res, next) => { req.io = null; next(); }, require('../backend/warehouse-routes').router);
        app.use((err, _req, res, _next) => res.status(500).json({ error: 'TEST_ERROR', message: err.message }));
        server = app.listen(0);
        baseUrl = `http://127.0.0.1:${server.address().port}/api/warehouse`;
        const sign = (user) => signAccessToken(user);
        adminToken = sign({ id: 1, username: 'admin', role: 'admin', name: 'المدير' });
        headSaladsToken = sign({ id: 9002, username: 'head_salads', role: 'dept_head', name: 'رئيس قسم السلطات', dept_code: 'salads' });
        keeperToken = sign({ id: 9007, username: 'keeper', role: 'warehouse', name: 'أمين المخازن' });
    });

    afterAll(async () => {
        // تنظيف ذاتي: حذف مصروفات الفحص بالمعرفات الموثقة فقط
        if (createdExpenseIds.length) {
            await pool.query('DELETE FROM expenses WHERE id = ANY($1::bigint[])', [createdExpenseIds]);
        }
        await pool.end().catch(() => {});
        server.close();
    });

    async function seedExpense(deptId, amount, adjustmentType, autoGen) {
        const row = (await pool.query(
            `INSERT INTO expenses (id, "deptId", "desc", amount, date, notes, "autoGenerated", category, "adjustmentType")
             VALUES ($1,$2,$3,$4,$5,$6,$7,'مواد خام',$8) RETURNING id`,
            [Date.now() + Math.floor(Math.random() * 999999), deptId, 'TEST dept-panel expense', amount,
             new Date().toISOString().slice(0, 10), 'test-cleanup', autoGen, adjustmentType]
        )).rows[0];
        createdExpenseIds.push(Number(row.id));
        return Number(row.id);
    }

    test('رئيس قسم السلطات يرى لوحة قسمه: نطاق مقفل + مصروفات مصنفة + أذونات', async () => {
        const marker = `TEST-pnl-${Date.now()}`;
        await seedExpense('salads', 25, 'dispatch', true);
        const res = await fetch(baseUrl + '/dept-panel', { headers: { Authorization: `Bearer ${headSaladsToken}` } });
        expect(res.status).toBe(200);
        const body = await res.json();
        expect(body.scope.view).toBe('department');
        expect(body.scope.deptCode).toBe('salads');
        expect(body.department.code).toBe('salads');
        expect(body.expenses.total).toBeGreaterThanOrEqual(25);
        expect(Object.keys(body.expenses.bySource)).toContain('dispatch');
        expect(body.dispatches).toHaveProperty('total');
    }, 20000);

    test('رئيس قسم يطلب لوحة قسم آخر → 403 DEPT_MISMATCH (لا IDOR)', async () => {
        const res = await fetch(baseUrl + '/dept-panel?dept=fnb', { headers: { Authorization: `Bearer ${headSaladsToken}` } });
        expect(res.status).toBe(403);
        expect((await res.json()).error).toBe('DEPT_MISMATCH');
    }, 20000);

    test('أمين المخازن (خارج الأدوار) → 403، والمجهول → 401', async () => {
        const denied = await fetch(baseUrl + '/dept-panel', { headers: { Authorization: `Bearer ${keeperToken}` } });
        expect(denied.status).toBe(403);
        const anon = await fetch(baseUrl + '/dept-panel');
        expect(anon.status).toBe(401);
    }, 20000);

    test('الشيف العمومي يرى المطبخ مع أقسامه الفرعية العشرة، وadmin يطلب قسمًا بعينه', async () => {
        const chefToken = signAccessToken({ id: 9001, username: 'chef', role: 'kitchen', name: 'الشيف العمومي', dept_code: null });
        const chefRes = await fetch(baseUrl + '/dept-panel', { headers: { Authorization: `Bearer ${chefToken}` } });
        expect(chefRes.status).toBe(200);
        const chefBody = await chefRes.json();
        expect(chefBody.scope.deptCode).toBe('kitchen');
        expect(chefBody.subDepartments.map(s => s.code).sort()).toEqual(['bakery', 'butcher', 'external_sales', 'fnb', 'hot_hall', 'hot_kitchen', 'kstore', 'open_buffet', 'salads', 'storeroom', 'sweets']);
        const adminRes = await fetch(baseUrl + '/dept-panel?dept=sweets', { headers: { Authorization: `Bearer ${adminToken}` } });
        expect(adminRes.status).toBe(200);
        expect((await adminRes.json()).department.code).toBe('sweets');
    }, 20000);
});
